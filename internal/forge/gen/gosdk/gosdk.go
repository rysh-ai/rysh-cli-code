// Package gosdk is a Forge generator that emits a self-contained Go client SDK
// for an API described by the IR. The generated package depends only on the
// standard library (net/http, encoding/json) and exposes one exported method
// per operation. Output is deterministic: operations are walked via
// api.SortedOperations() and all map keys are sorted before emission.
//
// The emitted Go source lives in the returned FileSet as string data; it is
// NOT compiled as part of this generator package (this file is the only thing
// that must build and be gofmt-clean here).
package gosdk

import (
	"fmt"
	"sort"
	"strings"

	"github.com/rysh-ai/rysh-cli-code/internal/forge/gen"
	"github.com/rysh-ai/rysh-cli-code/internal/forge/ir"
)

func init() { gen.Register(&generator{}) }

type generator struct{}

func (g *generator) Name() string { return "go-sdk" }

// Generate renders the API into a Go SDK FileSet (go.mod + client.go).
func (g *generator) Generate(api *ir.API, opts gen.Options) (*gen.FileSet, error) {
	fs := gen.NewFileSet()

	pkg := goSanitizePkg(opts.PackageName)
	if pkg == "" {
		pkg = goSanitizePkg(ir.Slugify(api.Name))
	}
	if pkg == "" {
		pkg = "client"
	}

	module := opts.ModulePath
	if module == "" {
		slug := ir.Slugify(api.Name)
		if slug == "" {
			slug = "client"
		}
		module = "example.com/" + slug
	}

	fs.AddString("go.mod", goMod(module))
	fs.AddString("client.go", goClient(api, pkg))
	return fs, nil
}

func goMod(module string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "module %s\n\ngo 1.21\n", module)
	return b.String()
}

func goClient(api *ir.API, pkg string) string {
	var b strings.Builder

	fmt.Fprintf(&b, "// Package %s is a generated Go client for %s.\n",
		pkg, oneLine(firstNonEmpty(api.Name, "the API")))
	if d := oneLine(api.Description); d != "" {
		fmt.Fprintf(&b, "//\n// %s\n", d)
	}
	fmt.Fprintf(&b, "//\n// Generated by Forge (go-sdk). Do not edit by hand.\n")
	fmt.Fprintf(&b, "package %s\n\n", pkg)

	b.WriteString("import (\n")
	b.WriteString("\t\"bytes\"\n")
	b.WriteString("\t\"encoding/base64\"\n")
	b.WriteString("\t\"encoding/json\"\n")
	b.WriteString("\t\"fmt\"\n")
	b.WriteString("\t\"io\"\n")
	b.WriteString("\t\"net/http\"\n")
	b.WriteString("\t\"net/url\"\n")
	b.WriteString("\t\"strings\"\n")
	b.WriteString(")\n\n")

	writeGoClientType(&b, api)
	writeGoConstructor(&b, api)
	writeGoDoRequest(&b, api)

	// Typed models for every named component schema. Emitted in sorted order so
	// the output is deterministic; $ref fields resolve to these named types.
	writeGoModels(&b, api)

	for _, op := range api.SortedOperations() {
		writeGoMethod(&b, api, op)
	}

	// Pagination iterators (one per paginated operation) plus the shared
	// generic-JSON helpers they rely on.
	writeGoPaginators(&b, api)

	return b.String()
}

// writeGoModels emits one exported struct per named component schema. Object
// schemas become structs (one field per property, JSON tags, ,omitempty on
// optional fields); non-object named schemas become type aliases so that $ref
// to them still resolves to a concrete named type. Fields are walked in sorted
// key order for deterministic output.
func writeGoModels(b *strings.Builder, api *ir.API) {
	names := make([]string, 0, len(api.Schemas))
	for n := range api.Schemas {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, name := range names {
		s := api.Schemas[name]
		typeName := goExportName(name)
		if typeName == "" {
			continue
		}
		if d := oneLine(descOf(s)); d != "" {
			fmt.Fprintf(b, "// %s: %s\n", typeName, d)
		} else {
			fmt.Fprintf(b, "// %s models the %q schema.\n", typeName, name)
		}
		if s == nil || (s.Type != "object" && len(s.Properties) == 0) {
			fmt.Fprintf(b, "type %s = %s\n\n", typeName, goRefType(api, s))
			continue
		}
		required := map[string]bool{}
		for _, r := range s.Required {
			required[r] = true
		}
		fmt.Fprintf(b, "type %s struct {\n", typeName)
		propNames := make([]string, 0, len(s.Properties))
		for pn := range s.Properties {
			propNames = append(propNames, pn)
		}
		sort.Strings(propNames)
		seen := map[string]bool{}
		for _, pn := range propNames {
			fld := goExportName(pn)
			if fld == "" {
				continue
			}
			if seen[fld] {
				fld = fld + "Field"
			}
			seen[fld] = true
			tag := pn
			if !required[pn] {
				tag += ",omitempty"
			}
			if d := oneLine(descOf(s.Properties[pn])); d != "" {
				fmt.Fprintf(b, "\t// %s\n", d)
			}
			fmt.Fprintf(b, "\t%s %s `json:\"%s\"`\n", fld, goRefType(api, s.Properties[pn]), tag)
		}
		b.WriteString("}\n\n")
	}
}

// writeGoPaginators emits a best-effort iterator per paginated operation and,
// if any exist, the shared generic-JSON page helpers.
//
// Iterator heuristic (each page is returned raw as json.RawMessage so callers
// decode against whatever shape they need):
//   - cursor: send PaginationHint.Param each call; after a page, read the next
//     token from PaginationHint.NextField (falling back to "next_cursor" /
//     "cursor") and stop when it is empty.
//   - page:   increment the page param by 1 each call; stop on an empty page.
//   - offset: advance the offset param by the number of items in the page; stop
//     on an empty page.
//
// "Empty page" is detected generically: a top-level JSON array of length 0, an
// empty "data"/"items"/"results" array, or an empty object. If the paging param
// is not a field on the request struct the iterator degrades to a single page,
// so it can never loop forever.
func writeGoPaginators(b *strings.Builder, api *ir.API) {
	var paginated []ir.Operation
	for _, op := range api.SortedOperations() {
		if op.Pagination != nil {
			paginated = append(paginated, op)
		}
	}
	if len(paginated) == 0 {
		return
	}
	for _, op := range paginated {
		writeGoPaginator(b, api, op)
	}
	writeGoPageHelpers(b)
}

func writeGoPaginator(b *strings.Builder, api *ir.API, op ir.Operation) {
	method := goExportName(op.ID)
	reqType := method + "Request"
	iterType := method + "Iterator"
	pg := op.Pagination

	pageParam := pg.Param
	if pageParam == "" {
		switch pg.Style {
		case "page":
			pageParam = "page"
		case "offset":
			pageParam = "offset"
		default:
			pageParam = "cursor"
		}
	}
	nextField := pg.NextField
	if nextField == "" {
		nextField = "next_cursor"
	}
	// Only operations whose request struct carries the paging param can advance.
	paramField := ""
	for _, p := range op.Params {
		if p.Name == pageParam {
			paramField = goExportName(p.Name)
			break
		}
	}
	canAdvance := paramField != ""

	fmt.Fprintf(b, "// %s iterates every page of %s (style %q, param %q).\n",
		iterType, method, pg.Style, pageParam)
	fmt.Fprintf(b, "type %s struct {\n", iterType)
	b.WriteString("\tclient *Client\n")
	fmt.Fprintf(b, "\treq    %s\n", reqType)
	b.WriteString("\tdone   bool\n")
	switch pg.Style {
	case "page":
		b.WriteString("\tpage   int\n")
	case "offset":
		b.WriteString("\toffset int\n")
	default:
		b.WriteString("\tcursor string\n")
	}
	b.WriteString("}\n\n")

	// Constructor on the client.
	fmt.Fprintf(b, "// %sAll returns an iterator over every page of %s.\n", method, method)
	fmt.Fprintf(b, "func (c *Client) %sAll(req %s) *%s {\n", method, reqType, iterType)
	switch pg.Style {
	case "page":
		fmt.Fprintf(b, "\treturn &%s{client: c, req: req, page: 1}\n", iterType)
	default:
		fmt.Fprintf(b, "\treturn &%s{client: c, req: req}\n", iterType)
	}
	b.WriteString("}\n\n")

	// Next.
	fmt.Fprintf(b, "// Next fetches the next page, returning (page, true, nil) while pages remain\n")
	fmt.Fprintf(b, "// and (nil, false, nil) once exhausted.\n")
	fmt.Fprintf(b, "func (it *%s) Next() (json.RawMessage, bool, error) {\n", iterType)
	b.WriteString("\tif it.done {\n\t\treturn nil, false, nil\n\t}\n")
	if canAdvance {
		switch pg.Style {
		case "page":
			fmt.Fprintf(b, "\tit.req.%s = it.page\n", paramField)
		case "offset":
			fmt.Fprintf(b, "\tit.req.%s = it.offset\n", paramField)
		default:
			fmt.Fprintf(b, "\tit.req.%s = it.cursor\n", paramField)
		}
	}
	fmt.Fprintf(b, "\tpage, err := it.client.%s(it.req)\n", method)
	b.WriteString("\tif err != nil {\n\t\treturn nil, false, err\n\t}\n")
	b.WriteString("\tif goPageCount(page) == 0 {\n\t\tit.done = true\n\t\treturn nil, false, nil\n\t}\n")
	if !canAdvance {
		// Cannot advance the paging parameter: yield this page once, then stop.
		b.WriteString("\tit.done = true\n")
		b.WriteString("\treturn page, true, nil\n")
		b.WriteString("}\n\n")
		return
	}
	switch pg.Style {
	case "page":
		b.WriteString("\tit.page++\n")
	case "offset":
		b.WriteString("\tit.offset += goPageCount(page)\n")
	default:
		fmt.Fprintf(b, "\tnext := goPageString(page, %s)\n", goQuote(nextField))
		b.WriteString("\tif next == \"\" {\n\t\tit.done = true\n\t} else {\n\t\tit.cursor = next\n\t}\n")
	}
	b.WriteString("\treturn page, true, nil\n")
	b.WriteString("}\n\n")
}

// writeGoPageHelpers emits the generic JSON inspection helpers shared by the
// pagination iterators. They are emitted only when at least one iterator exists.
func writeGoPageHelpers(b *strings.Builder) {
	b.WriteString("// goPageCount reports how many items a paginated response carries: a top-level\n")
	b.WriteString("// JSON array's length, else a \"data\"/\"items\"/\"results\" array's length, else 1\n")
	b.WriteString("// for a non-empty object and 0 for empty / unparseable input.\n")
	b.WriteString("func goPageCount(raw json.RawMessage) int {\n")
	b.WriteString("\tif len(raw) == 0 {\n\t\treturn 0\n\t}\n")
	b.WriteString("\tvar arr []json.RawMessage\n")
	b.WriteString("\tif err := json.Unmarshal(raw, &arr); err == nil {\n\t\treturn len(arr)\n\t}\n")
	b.WriteString("\tvar obj map[string]json.RawMessage\n")
	b.WriteString("\tif err := json.Unmarshal(raw, &obj); err != nil {\n\t\treturn 0\n\t}\n")
	b.WriteString("\tfor _, key := range []string{\"data\", \"items\", \"results\"} {\n")
	b.WriteString("\t\tif v, ok := obj[key]; ok {\n")
	b.WriteString("\t\t\tvar inner []json.RawMessage\n")
	b.WriteString("\t\t\tif err := json.Unmarshal(v, &inner); err == nil {\n\t\t\t\treturn len(inner)\n\t\t\t}\n")
	b.WriteString("\t\t}\n")
	b.WriteString("\t}\n")
	b.WriteString("\tif len(obj) == 0 {\n\t\treturn 0\n\t}\n")
	b.WriteString("\treturn 1\n")
	b.WriteString("}\n\n")

	b.WriteString("// goPageString extracts a top-level string field (e.g. the next cursor) from a\n")
	b.WriteString("// JSON object, returning \"\" when absent or not a string.\n")
	b.WriteString("func goPageString(raw json.RawMessage, field string) string {\n")
	b.WriteString("\tvar obj map[string]json.RawMessage\n")
	b.WriteString("\tif err := json.Unmarshal(raw, &obj); err != nil {\n\t\treturn \"\"\n\t}\n")
	b.WriteString("\tv, ok := obj[field]\n")
	b.WriteString("\tif !ok {\n\t\treturn \"\"\n\t}\n")
	b.WriteString("\tvar s string\n")
	b.WriteString("\tif err := json.Unmarshal(v, &s); err != nil {\n\t\treturn \"\"\n\t}\n")
	b.WriteString("\treturn s\n")
	b.WriteString("}\n\n")
}

func writeGoClientType(b *strings.Builder, api *ir.API) {
	b.WriteString("// Client calls the API over HTTP.\n")
	b.WriteString("type Client struct {\n")
	b.WriteString("\tBaseURL    string\n")
	b.WriteString("\tHTTPClient *http.Client\n")

	useAPIKey, useBasic := authNeeds(api)
	if useAPIKey {
		b.WriteString("\t// APIKey is the credential for apiKey / bearer / oauth2 schemes.\n")
		b.WriteString("\tApiKey string\n")
	}
	if useBasic {
		b.WriteString("\t// Username and Password back HTTP basic auth.\n")
		b.WriteString("\tUsername string\n")
		b.WriteString("\tPassword string\n")
	}
	b.WriteString("}\n\n")
}

func writeGoConstructor(b *strings.Builder, api *ir.API) {
	defBase := api.BaseURL()
	b.WriteString("// Option configures a Client.\n")
	b.WriteString("type Option func(*Client)\n\n")

	useAPIKey, useBasic := authNeeds(api)
	if useAPIKey {
		b.WriteString("// WithAPIKey sets the API key / bearer token credential.\n")
		b.WriteString("func WithAPIKey(key string) Option { return func(c *Client) { c.ApiKey = key } }\n\n")
	}
	if useBasic {
		b.WriteString("// WithBasicAuth sets HTTP basic auth credentials.\n")
		b.WriteString("func WithBasicAuth(user, pass string) Option {\n")
		b.WriteString("\treturn func(c *Client) { c.Username, c.Password = user, pass }\n")
		b.WriteString("}\n\n")
	}
	b.WriteString("// WithHTTPClient overrides the underlying *http.Client.\n")
	b.WriteString("func WithHTTPClient(h *http.Client) Option { return func(c *Client) { c.HTTPClient = h } }\n\n")

	b.WriteString("// New builds a Client. If baseURL is empty the API's default server is used.\n")
	b.WriteString("func New(baseURL string, opts ...Option) *Client {\n")
	b.WriteString("\tif baseURL == \"\" {\n")
	fmt.Fprintf(b, "\t\tbaseURL = %s\n", goQuote(defBase))
	b.WriteString("\t}\n")
	b.WriteString("\tc := &Client{BaseURL: strings.TrimRight(baseURL, \"/\"), HTTPClient: http.DefaultClient}\n")
	b.WriteString("\tfor _, o := range opts {\n")
	b.WriteString("\t\to(c)\n")
	b.WriteString("\t}\n")
	b.WriteString("\tif c.HTTPClient == nil {\n")
	b.WriteString("\t\tc.HTTPClient = http.DefaultClient\n")
	b.WriteString("\t}\n")
	b.WriteString("\treturn c\n")
	b.WriteString("}\n\n")
}

func writeGoDoRequest(b *strings.Builder, api *ir.API) {
	b.WriteString("func (c *Client) applyAuth(req *http.Request) {\n")
	for _, scheme := range api.Auth {
		switch scheme.Type {
		case "apiKey":
			switch scheme.In {
			case "header":
				fmt.Fprintf(b, "\tif c.ApiKey != \"\" {\n\t\treq.Header.Set(%s, c.ApiKey)\n\t}\n", goQuote(scheme.KeyName))
			case "query":
				fmt.Fprintf(b, "\tif c.ApiKey != \"\" {\n\t\tq := req.URL.Query()\n\t\tq.Set(%s, c.ApiKey)\n\t\treq.URL.RawQuery = q.Encode()\n\t}\n", goQuote(scheme.KeyName))
			}
		case "http":
			switch strings.ToLower(scheme.Scheme) {
			case "bearer":
				b.WriteString("\tif c.ApiKey != \"\" {\n\t\treq.Header.Set(\"Authorization\", \"Bearer \"+c.ApiKey)\n\t}\n")
			case "basic":
				b.WriteString("\tif c.Username != \"\" {\n\t\ttoken := base64.StdEncoding.EncodeToString([]byte(c.Username + \":\" + c.Password))\n\t\treq.Header.Set(\"Authorization\", \"Basic \"+token)\n\t}\n")
			}
		case "oauth2":
			b.WriteString("\tif c.ApiKey != \"\" {\n\t\treq.Header.Set(\"Authorization\", \"Bearer \"+c.ApiKey)\n\t}\n")
		}
	}
	b.WriteString("\t_ = base64.StdEncoding\n")
	b.WriteString("}\n\n")

	b.WriteString("// doRequest performs one HTTP call and returns the raw response body.\n")
	b.WriteString("func (c *Client) doRequest(method, path string, query url.Values, headers map[string]string, body any) (json.RawMessage, error) {\n")
	b.WriteString("\tu := c.BaseURL + path\n")
	b.WriteString("\tif enc := query.Encode(); enc != \"\" {\n")
	b.WriteString("\t\tu += \"?\" + enc\n")
	b.WriteString("\t}\n")
	b.WriteString("\tvar reader io.Reader\n")
	b.WriteString("\tif body != nil {\n")
	b.WriteString("\t\traw, err := json.Marshal(body)\n")
	b.WriteString("\t\tif err != nil {\n")
	b.WriteString("\t\t\treturn nil, err\n")
	b.WriteString("\t\t}\n")
	b.WriteString("\t\treader = bytes.NewReader(raw)\n")
	b.WriteString("\t}\n")
	b.WriteString("\treq, err := http.NewRequest(method, u, reader)\n")
	b.WriteString("\tif err != nil {\n")
	b.WriteString("\t\treturn nil, err\n")
	b.WriteString("\t}\n")
	b.WriteString("\treq.Header.Set(\"Accept\", \"application/json\")\n")
	b.WriteString("\tif body != nil {\n")
	b.WriteString("\t\treq.Header.Set(\"Content-Type\", \"application/json\")\n")
	b.WriteString("\t}\n")
	b.WriteString("\tfor k, v := range headers {\n")
	b.WriteString("\t\treq.Header.Set(k, v)\n")
	b.WriteString("\t}\n")
	b.WriteString("\tc.applyAuth(req)\n")
	b.WriteString("\tresp, err := c.HTTPClient.Do(req)\n")
	b.WriteString("\tif err != nil {\n")
	b.WriteString("\t\treturn nil, err\n")
	b.WriteString("\t}\n")
	b.WriteString("\tdefer resp.Body.Close()\n")
	b.WriteString("\tdata, err := io.ReadAll(resp.Body)\n")
	b.WriteString("\tif err != nil {\n")
	b.WriteString("\t\treturn nil, err\n")
	b.WriteString("\t}\n")
	b.WriteString("\tif resp.StatusCode < 200 || resp.StatusCode >= 300 {\n")
	b.WriteString("\t\treturn nil, fmt.Errorf(\"%s %s -> HTTP %d: %s\", method, path, resp.StatusCode, string(data))\n")
	b.WriteString("\t}\n")
	b.WriteString("\treturn json.RawMessage(data), nil\n")
	b.WriteString("}\n\n")

	b.WriteString("func toStr(v any) string {\n")
	b.WriteString("\tif v == nil {\n")
	b.WriteString("\t\treturn \"\"\n")
	b.WriteString("\t}\n")
	b.WriteString("\tif s, ok := v.(string); ok {\n")
	b.WriteString("\t\treturn s\n")
	b.WriteString("\t}\n")
	b.WriteString("\treturn fmt.Sprintf(\"%v\", v)\n")
	b.WriteString("}\n\n")
	b.WriteString("var _ = url.PathEscape\n\n")
}

func writeGoMethod(b *strings.Builder, api *ir.API, op ir.Operation) {
	method := goExportName(op.ID)
	reqType := method + "Request"

	pathParams, queryParams, headerParams := splitParams(op)
	bodyFields := goBodyFields(api, op)

	// Request struct.
	if summary := oneLine(firstNonEmpty(op.Summary, op.Description)); summary != "" {
		fmt.Fprintf(b, "// %s is the request for %s.\n", reqType, method)
	}
	fmt.Fprintf(b, "type %s struct {\n", reqType)
	seen := map[string]bool{}
	for _, p := range append(append(append([]ir.Param{}, pathParams...), queryParams...), headerParams...) {
		fld := goExportName(p.Name)
		if seen[fld] {
			continue
		}
		seen[fld] = true
		if d := oneLine(p.Description); d != "" {
			fmt.Fprintf(b, "\t// %s\n", d)
		}
		fmt.Fprintf(b, "\t%s %s `json:\"%s,omitempty\"`\n", fld, goType(p.Schema), p.Name)
	}
	for _, f := range bodyFields {
		fld := goExportName(f.name)
		if seen[fld] {
			fld = fld + "Body"
		}
		seen[fld] = true
		if d := oneLine(f.desc); d != "" {
			fmt.Fprintf(b, "\t// %s\n", d)
		}
		fmt.Fprintf(b, "\t%s %s `json:\"%s,omitempty\"`\n", fld, f.gotype, f.name)
	}
	b.WriteString("}\n\n")

	// Method.
	if summary := oneLine(firstNonEmpty(op.Summary, op.Description)); summary != "" {
		fmt.Fprintf(b, "// %s %s\n", method, summary)
	}
	fmt.Fprintf(b, "// %s %s\n", op.Method, op.Path)
	fmt.Fprintf(b, "func (c *Client) %s(req %s) (json.RawMessage, error) {\n", method, reqType)

	// Path.
	fmt.Fprintf(b, "\tpath := %s\n", goQuote(op.Path))
	for _, p := range pathParams {
		fld := goExportName(p.Name)
		fmt.Fprintf(b, "\tpath = strings.ReplaceAll(path, %s, url.PathEscape(toStr(req.%s)))\n",
			goQuote("{"+p.Name+"}"), fld)
	}

	// Query.
	b.WriteString("\tquery := url.Values{}\n")
	for _, p := range queryParams {
		fld := goExportName(p.Name)
		fmt.Fprintf(b, "\tquery.Set(%s, toStr(req.%s))\n", goQuote(p.Name), fld)
	}

	// Headers.
	b.WriteString("\theaders := map[string]string{}\n")
	for _, p := range headerParams {
		fld := goExportName(p.Name)
		fmt.Fprintf(b, "\theaders[%s] = toStr(req.%s)\n", goQuote(p.Name), fld)
	}

	// Body.
	if op.Mutating && len(bodyFields) > 0 {
		b.WriteString("\tbody := map[string]any{}\n")
		bodySeen := map[string]bool{}
		for _, p := range append(append([]ir.Param{}, pathParams...), append(queryParams, headerParams...)...) {
			bodySeen[goExportName(p.Name)] = true
		}
		for _, f := range bodyFields {
			fld := goExportName(f.name)
			if bodySeen[fld] {
				fld = fld + "Body"
			}
			fmt.Fprintf(b, "\tbody[%s] = req.%s\n", goQuote(f.name), fld)
		}
		b.WriteString("\treturn c.doRequest(" + goQuote(op.Method) + ", path, query, headers, body)\n")
	} else if op.Mutating {
		b.WriteString("\treturn c.doRequest(" + goQuote(op.Method) + ", path, query, headers, struct{}{})\n")
	} else {
		b.WriteString("\treturn c.doRequest(" + goQuote(op.Method) + ", path, query, headers, nil)\n")
	}
	b.WriteString("}\n\n")
}

// goBodyField is one synthetic request-body field.
type goBodyField struct {
	name   string
	gotype string
	desc   string
}

// goBodyFields derives the request-body fields for an operation, mirroring the
// runtime's flat-args convention: an object body contributes its properties; a
// non-object body is wrapped under "body".
func goBodyFields(api *ir.API, op ir.Operation) []goBodyField {
	if op.RequestBody == nil {
		return nil
	}
	body := api.Resolve(op.RequestBody)
	if body == nil {
		return nil
	}
	if body.Type == "object" || len(body.Properties) > 0 {
		names := make([]string, 0, len(body.Properties))
		for n := range body.Properties {
			names = append(names, n)
		}
		sort.Strings(names)
		out := make([]goBodyField, 0, len(names))
		for _, n := range names {
			ps := body.Properties[n]
			out = append(out, goBodyField{name: n, gotype: goRefType(api, ps), desc: descOf(ps)})
		}
		return out
	}
	return []goBodyField{{name: "body", gotype: goRefType(api, body), desc: descOf(body)}}
}

func authNeeds(api *ir.API) (apiKey, basic bool) {
	for _, s := range api.Auth {
		switch s.Type {
		case "apiKey", "oauth2":
			apiKey = true
		case "http":
			if strings.ToLower(s.Scheme) == "basic" {
				basic = true
			} else {
				apiKey = true
			}
		}
	}
	if len(api.Auth) == 0 {
		apiKey = true // permit a bearer token even when unspecified
	}
	return apiKey, basic
}

func splitParams(op ir.Operation) (path, query, header []ir.Param) {
	for _, p := range op.Params {
		switch p.In {
		case "path":
			path = append(path, p)
		case "query":
			query = append(query, p)
		case "header":
			header = append(header, p)
		}
	}
	return path, query, header
}

func goType(s *ir.Schema) string {
	if s == nil {
		return "string"
	}
	switch s.Type {
	case "integer":
		return "int"
	case "number":
		return "float64"
	case "boolean":
		return "bool"
	case "array":
		return "[]" + goType(s.Items)
	case "object":
		return "map[string]any"
	case "string":
		return "string"
	}
	if len(s.Properties) > 0 {
		return "map[string]any"
	}
	return "string"
}

// goRefType is like goType but resolves a $ref to the exported name of the
// generated model struct (as a pointer), so typed models reference each other
// by name. A ref to an unknown schema, or a non-object resolved schema, falls
// back to the plain scalar/composite type. Used for model fields and request
// bodies; param types keep using goType (params are always scalars).
func goRefType(api *ir.API, s *ir.Schema) string {
	if s == nil {
		return "any"
	}
	if s.Ref != "" {
		if api != nil {
			if named, ok := api.Schemas[s.Ref]; ok && named != nil {
				tn := goExportName(s.Ref)
				if tn != "" {
					// Alias types (non-object) are value types; struct types are
					// referenced via pointer so optional/omitempty works.
					if named.Type == "object" || len(named.Properties) > 0 {
						return "*" + tn
					}
					return tn
				}
			}
		}
		return "map[string]any"
	}
	switch s.Type {
	case "integer":
		return "int"
	case "number":
		return "float64"
	case "boolean":
		return "bool"
	case "array":
		return "[]" + goRefType(api, s.Items)
	case "string":
		return "string"
	case "object":
		return "map[string]any"
	}
	if len(s.Properties) > 0 {
		return "map[string]any"
	}
	return "string"
}

func descOf(s *ir.Schema) string {
	if s == nil {
		return ""
	}
	return s.Description
}

// goExportName converts an arbitrary identifier into an exported Go CamelCase
// name. Non-alphanumeric runes act as word separators.
func goExportName(s string) string {
	var b strings.Builder
	upper := true
	for _, r := range s {
		switch {
		case r >= 'a' && r <= 'z':
			if upper {
				b.WriteRune(r - 32)
				upper = false
			} else {
				b.WriteRune(r)
			}
		case r >= 'A' && r <= 'Z':
			b.WriteRune(r)
			upper = false
		case r >= '0' && r <= '9':
			if b.Len() == 0 {
				b.WriteByte('X')
			}
			b.WriteRune(r)
			upper = false
		default:
			upper = true
		}
	}
	out := b.String()
	if out == "" {
		return "Op"
	}
	return out
}

func goSanitizePkg(s string) string {
	var b strings.Builder
	for _, r := range strings.ToLower(s) {
		switch {
		case r >= 'a' && r <= 'z', r >= '0' && r <= '9':
			b.WriteRune(r)
		}
	}
	out := b.String()
	if out != "" && out[0] >= '0' && out[0] <= '9' {
		out = "pkg" + out
	}
	return out
}

func goQuote(s string) string { return fmt.Sprintf("%q", s) }

func oneLine(s string) string {
	s = strings.TrimSpace(s)
	if i := strings.IndexByte(s, '\n'); i >= 0 {
		s = strings.TrimSpace(s[:i])
	}
	if len(s) > 200 {
		s = s[:199] + "…"
	}
	return s
}

func firstNonEmpty(vals ...string) string {
	for _, v := range vals {
		if strings.TrimSpace(v) != "" {
			return v
		}
	}
	return ""
}
