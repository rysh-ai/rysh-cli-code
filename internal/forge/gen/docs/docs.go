// Package docs generates Markdown API reference documentation from the IR.
package docs

import (
	"fmt"
	"sort"
	"strings"

	"github.com/rysh-ai/rysh-cli-code/internal/forge/gen"
	"github.com/rysh-ai/rysh-cli-code/internal/forge/ir"
)

func init() { gen.Register(&generator{}) }

type generator struct{}

func (g *generator) Name() string { return "docs" }

func (g *generator) Generate(api *ir.API, _ gen.Options) (*gen.FileSet, error) {
	fs := gen.NewFileSet()
	fs.AddString("reference.md", reference(api))
	fs.AddString("README.md", index(api))
	return fs, nil
}

func index(api *ir.API) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# %s\n\n", api.Name)
	if api.Description != "" {
		fmt.Fprintf(&b, "%s\n\n", api.Description)
	}
	fmt.Fprintf(&b, "- Version: `%s`\n", api.Version)
	if url := api.BaseURL(); url != "" {
		fmt.Fprintf(&b, "- Base URL: `%s`\n", url)
	}
	fmt.Fprintf(&b, "- Operations: %d\n\n", len(api.Operations))
	fmt.Fprintf(&b, "See [reference.md](./reference.md) for the full endpoint reference.\n\n")
	fmt.Fprintf(&b, "_Generated by Rysh Forge._\n")
	return b.String()
}

func reference(api *ir.API) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# %s — API Reference\n\n", api.Name)
	if api.Description != "" {
		fmt.Fprintf(&b, "%s\n\n", api.Description)
	}
	fmt.Fprintf(&b, "Version `%s`", api.Version)
	if url := api.BaseURL(); url != "" {
		fmt.Fprintf(&b, " · Base URL `%s`", url)
	}
	b.WriteString("\n\n")

	if len(api.Auth) > 0 {
		b.WriteString("## Authentication\n\n")
		for _, a := range api.Auth {
			switch a.Type {
			case "apiKey":
				fmt.Fprintf(&b, "- **%s** — API key in %s `%s`\n", a.Name, a.In, a.KeyName)
			case "http":
				fmt.Fprintf(&b, "- **%s** — HTTP %s\n", a.Name, a.Scheme)
			default:
				fmt.Fprintf(&b, "- **%s** — %s\n", a.Name, a.Type)
			}
		}
		b.WriteString("\n")
	}

	b.WriteString("## Endpoints\n\n")
	ops := api.SortedOperations()
	for i := range ops {
		op := &ops[i]
		fmt.Fprintf(&b, "### `%s` — %s %s\n\n", op.ID, op.Method, op.Path)
		if s := firstNonEmpty(op.Summary, op.Description); s != "" {
			fmt.Fprintf(&b, "%s\n\n", s)
		}
		if op.Mutating {
			b.WriteString("> ⚠️ Mutating endpoint — requires approval when called by an agent.\n\n")
		}
		if len(op.Params) > 0 {
			b.WriteString("| Parameter | In | Required | Type | Description |\n")
			b.WriteString("|---|---|---|---|---|\n")
			params := append([]ir.Param(nil), op.Params...)
			sort.Slice(params, func(i, j int) bool { return params[i].Name < params[j].Name })
			for _, p := range params {
				typ := "string"
				if p.Schema != nil && p.Schema.Type != "" {
					typ = p.Schema.Type
				}
				fmt.Fprintf(&b, "| `%s` | %s | %v | %s | %s |\n", p.Name, p.In, p.Required, typ, oneLine(p.Description))
			}
			b.WriteString("\n")
		}
		if op.RequestBody != nil {
			body := api.Resolve(op.RequestBody)
			if body != nil && len(body.Required) > 0 {
				fmt.Fprintf(&b, "Request body required fields: %s\n\n", "`"+strings.Join(body.Required, "`, `")+"`")
			} else {
				b.WriteString("Accepts a JSON request body.\n\n")
			}
		}
		codes := make([]string, 0, len(op.Responses))
		for c := range op.Responses {
			codes = append(codes, c)
		}
		sort.Strings(codes)
		if len(codes) > 0 {
			fmt.Fprintf(&b, "Responses: %s\n\n", "`"+strings.Join(codes, "`, `")+"`")
		}
		b.WriteString("---\n\n")
	}
	fmt.Fprintf(&b, "_Generated by Rysh Forge from a %s source._\n", api.SourceType)
	return b.String()
}

func firstNonEmpty(a, b string) string {
	if strings.TrimSpace(a) != "" {
		return a
	}
	return b
}

func oneLine(s string) string {
	s = strings.ReplaceAll(s, "\n", " ")
	s = strings.ReplaceAll(s, "|", "\\|")
	if len(s) > 120 {
		s = s[:119] + "…"
	}
	return strings.TrimSpace(s)
}
