// Package javasdk is a Forge generator that emits a Java client SDK for an API
// described by the IR. The generated client uses only the JDK (java.net.http
// HttpClient, available since Java 11) plus a tiny embedded JSON reader, so it
// has zero third-party dependencies. Output is deterministic: operations are
// walked via api.SortedOperations() and all map keys are sorted before emission.
//
// The emitted Java source is string data in the returned FileSet; it is NOT
// compiled by this generator — only this Go file must build and be gofmt-clean.
package javasdk

import (
	"fmt"
	"sort"
	"strings"

	"github.com/rysh-ai/rysh-cli-code/internal/forge/gen"
	"github.com/rysh-ai/rysh-cli-code/internal/forge/ir"
)

func init() { gen.Register(&generator{}) }

type generator struct{}

func (g *generator) Name() string { return "java-sdk" }

const basePackage = "com.rysh.forge.client"

// Generate renders the API into a Java SDK FileSet: a Maven pom.xml, the main
// Client.java, one model class per named schema, and a README.
func (g *generator) Generate(api *ir.API, opts gen.Options) (*gen.FileSet, error) {
	fs := gen.NewFileSet()

	artifact := opts.PackageName
	if artifact == "" {
		artifact = ir.Slugify(api.Name)
	}
	if artifact == "" {
		artifact = "api-client"
	}

	srcDir := "src/main/java/" + strings.ReplaceAll(basePackage, ".", "/")

	fs.AddString("pom.xml", javaPom(artifact, api))
	fs.AddString(srcDir+"/Client.java", javaClient(api))
	fs.AddString(srcDir+"/ApiException.java", javaAPIException())
	fs.AddString(srcDir+"/Json.java", javaJSON())

	// One model class per named component schema.
	for _, name := range sortedSchemaNames(api) {
		cls := javaClassName(name)
		if cls == "" {
			continue
		}
		fs.AddString(srcDir+"/model/"+cls+".java", javaModel(api, name))
	}

	fs.AddString("README.md", javaReadme(artifact, api))
	return fs, nil
}

func javaPom(artifact string, api *ir.API) string {
	version := strings.TrimSpace(api.Version)
	if version == "" {
		version = "0.1.0"
	}
	var b strings.Builder
	b.WriteString("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n")
	b.WriteString("<project xmlns=\"http://maven.apache.org/POM/4.0.0\"\n")
	b.WriteString("         xmlns:xsi=\"http://www.w3.org/2001/XMLSchema-instance\"\n")
	b.WriteString("         xsi:schemaLocation=\"http://maven.apache.org/POM/4.0.0 http://maven.apache.org/xsd/maven-4.0.0.xsd\">\n")
	b.WriteString("  <modelVersion>4.0.0</modelVersion>\n")
	b.WriteString("  <groupId>com.rysh.forge</groupId>\n")
	fmt.Fprintf(&b, "  <artifactId>%s</artifactId>\n", xmlEscape(artifact))
	fmt.Fprintf(&b, "  <version>%s</version>\n", xmlEscape(version))
	b.WriteString("  <packaging>jar</packaging>\n")
	b.WriteString("  <properties>\n")
	b.WriteString("    <maven.compiler.release>11</maven.compiler.release>\n")
	b.WriteString("    <project.build.sourceEncoding>UTF-8</project.build.sourceEncoding>\n")
	b.WriteString("  </properties>\n")
	b.WriteString("  <!-- Zero third-party dependencies: JDK java.net.http only. -->\n")
	b.WriteString("</project>\n")
	return b.String()
}

func javaReadme(artifact string, api *ir.API) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# %s\n\n", artifact)
	if d := oneLine(api.Description); d != "" {
		fmt.Fprintf(&b, "%s\n\n", d)
	}
	b.WriteString("Generated by Forge (java-sdk). JDK-only (Java 11+, `java.net.http`); no dependencies.\n\n")
	b.WriteString("```java\n")
	fmt.Fprintf(&b, "import %s.Client;\n\n", basePackage)
	fmt.Fprintf(&b, "Client client = Client.builder().baseUrl(%s).apiKey(\"...\").build();\n", javaStr(api.BaseURL()))
	if ops := api.SortedOperations(); len(ops) > 0 {
		fmt.Fprintf(&b, "String json = client.%s(new Client.%sRequest());\n", javaMethodName(ops[0].ID), javaClassName(ops[0].ID))
	}
	b.WriteString("```\n")
	return b.String()
}

func javaAPIException() string {
	var b strings.Builder
	fmt.Fprintf(&b, "package %s;\n\n", basePackage)
	b.WriteString("/** Thrown when the API returns a non-2xx HTTP status. */\n")
	b.WriteString("public class ApiException extends RuntimeException {\n")
	b.WriteString("    public final int statusCode;\n")
	b.WriteString("    public final String body;\n\n")
	b.WriteString("    public ApiException(int statusCode, String body) {\n")
	b.WriteString("        super(\"HTTP \" + statusCode + \": \" + body);\n")
	b.WriteString("        this.statusCode = statusCode;\n")
	b.WriteString("        this.body = body;\n")
	b.WriteString("    }\n")
	b.WriteString("}\n")
	return b.String()
}

func javaClient(api *ir.API) string {
	var b strings.Builder

	fmt.Fprintf(&b, "package %s;\n\n", basePackage)
	b.WriteString("import java.net.URI;\n")
	b.WriteString("import java.net.URLEncoder;\n")
	b.WriteString("import java.net.http.HttpClient;\n")
	b.WriteString("import java.net.http.HttpRequest;\n")
	b.WriteString("import java.net.http.HttpResponse;\n")
	b.WriteString("import java.nio.charset.StandardCharsets;\n")
	b.WriteString("import java.util.Base64;\n")
	b.WriteString("import java.util.LinkedHashMap;\n")
	b.WriteString("import java.util.Map;\n\n")

	if d := oneLine(firstNonEmpty(api.Name, "the API")); d != "" {
		fmt.Fprintf(&b, "/**\n * Generated Java client for %s.\n", d)
		if desc := oneLine(api.Description); desc != "" {
			fmt.Fprintf(&b, " * <p>%s\n", javaDoc(desc))
		}
		b.WriteString(" * <p>Generated by Forge (java-sdk). Do not edit by hand.\n */\n")
	}
	b.WriteString("public final class Client {\n")
	fmt.Fprintf(&b, "    public static final String DEFAULT_BASE_URL = %s;\n\n", javaStr(api.BaseURL()))

	b.WriteString("    private final String baseUrl;\n")
	b.WriteString("    private final String apiKey;\n")
	b.WriteString("    private final String username;\n")
	b.WriteString("    private final String password;\n")
	b.WriteString("    private final HttpClient http;\n\n")

	// Constructor + builder.
	b.WriteString("    private Client(Builder bld) {\n")
	b.WriteString("        String b = bld.baseUrl != null && !bld.baseUrl.isEmpty() ? bld.baseUrl : DEFAULT_BASE_URL;\n")
	b.WriteString("        while (b.endsWith(\"/\")) { b = b.substring(0, b.length() - 1); }\n")
	b.WriteString("        this.baseUrl = b;\n")
	b.WriteString("        this.apiKey = bld.apiKey;\n")
	b.WriteString("        this.username = bld.username;\n")
	b.WriteString("        this.password = bld.password;\n")
	b.WriteString("        this.http = bld.http != null ? bld.http : HttpClient.newHttpClient();\n")
	b.WriteString("    }\n\n")

	b.WriteString("    public static Builder builder() { return new Builder(); }\n\n")
	b.WriteString("    /** Fluent builder for {@link Client}. */\n")
	b.WriteString("    public static final class Builder {\n")
	b.WriteString("        private String baseUrl;\n")
	b.WriteString("        private String apiKey;\n")
	b.WriteString("        private String username;\n")
	b.WriteString("        private String password;\n")
	b.WriteString("        private HttpClient http;\n")
	b.WriteString("        public Builder baseUrl(String v) { this.baseUrl = v; return this; }\n")
	b.WriteString("        public Builder apiKey(String v) { this.apiKey = v; return this; }\n")
	b.WriteString("        public Builder basicAuth(String user, String pass) { this.username = user; this.password = pass; return this; }\n")
	b.WriteString("        public Builder httpClient(HttpClient v) { this.http = v; return this; }\n")
	b.WriteString("        public Client build() { return new Client(this); }\n")
	b.WriteString("    }\n\n")

	writeJavaAuth(&b, api)
	writeJavaDoRequest(&b)
	writeJavaHelpers(&b)

	for _, op := range api.SortedOperations() {
		writeJavaMethod(&b, api, op)
	}

	// Pagination iterators (one inner class per paginated operation) + helpers.
	writeJavaPaginators(&b, api)

	b.WriteString("}\n")
	return b.String()
}

func writeJavaAuth(b *strings.Builder, api *ir.API) {
	b.WriteString("    private void applyAuth(Map<String, String> headers, Map<String, String> query) {\n")
	for _, scheme := range api.Auth {
		switch scheme.Type {
		case "apiKey":
			switch scheme.In {
			case "header":
				fmt.Fprintf(b, "        if (apiKey != null && !apiKey.isEmpty()) { headers.put(%s, apiKey); }\n", javaStr(scheme.KeyName))
			case "query":
				fmt.Fprintf(b, "        if (apiKey != null && !apiKey.isEmpty()) { query.put(%s, apiKey); }\n", javaStr(scheme.KeyName))
			}
		case "http":
			switch strings.ToLower(scheme.Scheme) {
			case "bearer":
				b.WriteString("        if (apiKey != null && !apiKey.isEmpty()) { headers.put(\"Authorization\", \"Bearer \" + apiKey); }\n")
			case "basic":
				b.WriteString("        if (username != null && !username.isEmpty()) {\n")
				b.WriteString("            String raw = username + \":\" + (password == null ? \"\" : password);\n")
				b.WriteString("            headers.put(\"Authorization\", \"Basic \" + Base64.getEncoder().encodeToString(raw.getBytes(StandardCharsets.UTF_8)));\n")
				b.WriteString("        }\n")
			}
		case "oauth2":
			b.WriteString("        if (apiKey != null && !apiKey.isEmpty()) { headers.put(\"Authorization\", \"Bearer \" + apiKey); }\n")
		}
	}
	b.WriteString("    }\n\n")
}

func writeJavaDoRequest(b *strings.Builder) {
	b.WriteString("    private String doRequest(String method, String path, Map<String, String> query,\n")
	b.WriteString("                             Map<String, String> headers, String body) {\n")
	b.WriteString("        applyAuth(headers, query);\n")
	b.WriteString("        StringBuilder url = new StringBuilder(baseUrl).append(path);\n")
	b.WriteString("        boolean first = true;\n")
	b.WriteString("        for (Map.Entry<String, String> e : query.entrySet()) {\n")
	b.WriteString("            if (e.getValue() == null) { continue; }\n")
	b.WriteString("            url.append(first ? '?' : '&').append(enc(e.getKey())).append('=').append(enc(e.getValue()));\n")
	b.WriteString("            first = false;\n")
	b.WriteString("        }\n")
	b.WriteString("        HttpRequest.Builder rb = HttpRequest.newBuilder().uri(URI.create(url.toString()));\n")
	b.WriteString("        rb.header(\"Accept\", \"application/json\");\n")
	b.WriteString("        HttpRequest.BodyPublisher pub;\n")
	b.WriteString("        if (body != null) {\n")
	b.WriteString("            pub = HttpRequest.BodyPublishers.ofString(body, StandardCharsets.UTF_8);\n")
	b.WriteString("            rb.header(\"Content-Type\", \"application/json\");\n")
	b.WriteString("        } else {\n")
	b.WriteString("            pub = HttpRequest.BodyPublishers.noBody();\n")
	b.WriteString("        }\n")
	b.WriteString("        rb.method(method, pub);\n")
	b.WriteString("        for (Map.Entry<String, String> e : headers.entrySet()) {\n")
	b.WriteString("            if (e.getValue() != null) { rb.header(e.getKey(), e.getValue()); }\n")
	b.WriteString("        }\n")
	b.WriteString("        try {\n")
	b.WriteString("            HttpResponse<String> resp = http.send(rb.build(), HttpResponse.BodyHandlers.ofString());\n")
	b.WriteString("            if (resp.statusCode() < 200 || resp.statusCode() >= 300) {\n")
	b.WriteString("                throw new ApiException(resp.statusCode(), resp.body());\n")
	b.WriteString("            }\n")
	b.WriteString("            return resp.body();\n")
	b.WriteString("        } catch (java.io.IOException | InterruptedException ex) {\n")
	b.WriteString("            if (ex instanceof InterruptedException) { Thread.currentThread().interrupt(); }\n")
	b.WriteString("            throw new RuntimeException(method + \" \" + path + \" failed: \" + ex.getMessage(), ex);\n")
	b.WriteString("        }\n")
	b.WriteString("    }\n\n")
}

func writeJavaHelpers(b *strings.Builder) {
	b.WriteString("    private static String enc(String s) {\n")
	b.WriteString("        return URLEncoder.encode(s == null ? \"\" : s, StandardCharsets.UTF_8);\n")
	b.WriteString("    }\n\n")
	b.WriteString("    private static String str(Object v) { return v == null ? null : String.valueOf(v); }\n\n")
}

func writeJavaMethod(b *strings.Builder, api *ir.API, op ir.Operation) {
	method := javaMethodName(op.ID)
	reqClass := javaClassName(op.ID) + "Request"

	pathParams, queryParams, headerParams := splitParams(op)
	bodyFields := javaBodyFields(api, op)

	// Request class (public static, mutable fields for simplicity).
	if summary := oneLine(firstNonEmpty(op.Summary, op.Description)); summary != "" {
		fmt.Fprintf(b, "    /** Request for {@link #%s}. */\n", method)
	}
	fmt.Fprintf(b, "    public static final class %s {\n", reqClass)
	seen := map[string]bool{}
	emitField := func(name string, typ string, desc string) {
		fld := javaFieldName(name)
		if fld == "" || seen[fld] {
			return
		}
		seen[fld] = true
		if d := oneLine(desc); d != "" {
			fmt.Fprintf(b, "        /** %s */\n", javaDoc(d))
		}
		fmt.Fprintf(b, "        public %s %s;\n", typ, fld)
	}
	// All request fields use boxed/reference types so they are nullable (omittable
	// from the request) and the generated `field != null` guards compile — a
	// primitive (double/long/boolean) cannot be compared to null.
	for _, p := range pathParams {
		emitField(p.Name, boxedType(javaType(p.Schema)), p.Description)
	}
	for _, p := range queryParams {
		emitField(p.Name, boxedType(javaType(p.Schema)), p.Description)
	}
	for _, p := range headerParams {
		emitField(p.Name, boxedType(javaType(p.Schema)), p.Description)
	}
	for _, f := range bodyFields {
		emitField(f.name, boxedType(javaRefType(api, f.schema)), descOf(f.schema))
	}
	b.WriteString("    }\n\n")

	// Method.
	if summary := oneLine(firstNonEmpty(op.Summary, op.Description)); summary != "" {
		fmt.Fprintf(b, "    /**\n     * %s\n     * <p>%s %s\n     */\n", javaDoc(summary), op.Method, op.Path)
	} else {
		fmt.Fprintf(b, "    /** %s %s */\n", op.Method, op.Path)
	}
	fmt.Fprintf(b, "    public String %s(%s req) {\n", method, reqClass)
	b.WriteString("        if (req == null) { req = new " + reqClass + "(); }\n")

	// Path.
	fmt.Fprintf(b, "        String path = %s;\n", javaStr(op.Path))
	for _, p := range pathParams {
		fld := javaFieldName(p.Name)
		fmt.Fprintf(b, "        path = path.replace(%s, enc(str(req.%s)));\n", javaStr("{"+p.Name+"}"), fld)
	}

	// Query.
	b.WriteString("        Map<String, String> query = new LinkedHashMap<>();\n")
	for _, p := range queryParams {
		fld := javaFieldName(p.Name)
		fmt.Fprintf(b, "        if (req.%s != null) { query.put(%s, str(req.%s)); }\n", fld, javaStr(p.Name), fld)
	}

	// Headers.
	b.WriteString("        Map<String, String> headers = new LinkedHashMap<>();\n")
	for _, p := range headerParams {
		fld := javaFieldName(p.Name)
		fmt.Fprintf(b, "        if (req.%s != null) { headers.put(%s, str(req.%s)); }\n", fld, javaStr(p.Name), fld)
	}

	// Body.
	if op.Mutating && len(bodyFields) > 0 {
		b.WriteString("        Map<String, Object> body = new LinkedHashMap<>();\n")
		for _, f := range bodyFields {
			fld := javaFieldName(f.name)
			fmt.Fprintf(b, "        if (req.%s != null) { body.put(%s, req.%s); }\n", fld, javaStr(f.name), fld)
		}
		fmt.Fprintf(b, "        return doRequest(%s, path, query, headers, Json.encode(body));\n", javaStr(op.Method))
	} else if op.Mutating {
		fmt.Fprintf(b, "        return doRequest(%s, path, query, headers, \"{}\");\n", javaStr(op.Method))
	} else {
		fmt.Fprintf(b, "        return doRequest(%s, path, query, headers, null);\n", javaStr(op.Method))
	}
	b.WriteString("    }\n\n")
}

// writeJavaPaginators emits one PagedIterator inner class per paginated operation
// plus a static helper. Each page is returned raw as a JSON String; callers parse
// it. Heuristic mirrors the other SDKs:
//   - cursor: send the paging param each call; read the next token from
//     PaginationHint.NextField (fallback "next_cursor") and stop when empty.
//   - page:   increment the page param; stop on an empty page.
//   - offset: advance the offset by the page's item count; stop on an empty page.
//
// "Empty page" is a top-level [] of length 0, an empty data/items/results array,
// or an empty object. If the paging param is not a request field the iterator
// yields a single page then stops, so it can never loop forever.
func writeJavaPaginators(b *strings.Builder, api *ir.API) {
	var paginated []ir.Operation
	for _, op := range api.SortedOperations() {
		if op.Pagination != nil {
			paginated = append(paginated, op)
		}
	}
	if len(paginated) == 0 {
		return
	}
	for _, op := range paginated {
		writeJavaPaginator(b, api, op)
	}
	writeJavaPageHelpers(b)
}

func writeJavaPaginator(b *strings.Builder, api *ir.API, op ir.Operation) {
	method := javaMethodName(op.ID)
	reqClass := javaClassName(op.ID) + "Request"
	iterClass := javaClassName(op.ID) + "Pager"
	pg := op.Pagination

	pageParam := pg.Param
	if pageParam == "" {
		switch pg.Style {
		case "page":
			pageParam = "page"
		case "offset":
			pageParam = "offset"
		default:
			pageParam = "cursor"
		}
	}
	nextField := pg.NextField
	if nextField == "" {
		nextField = "next_cursor"
	}
	paramField := ""
	for _, p := range op.Params {
		if p.Name == pageParam {
			paramField = javaFieldName(p.Name)
			break
		}
	}
	canAdvance := paramField != ""

	fmt.Fprintf(b, "    /** Iterates every page of {@link #%s} (style %s, param %s). */\n", method, pg.Style, pageParam)
	fmt.Fprintf(b, "    public %s %sPaged(%s req) { return new %s(req); }\n\n", iterClass, method, reqClass, iterClass)

	fmt.Fprintf(b, "    public final class %s implements java.util.Iterator<String> {\n", iterClass)
	fmt.Fprintf(b, "        private final %s req;\n", reqClass)
	b.WriteString("        private boolean done;\n")
	b.WriteString("        private String pending;\n")
	switch pg.Style {
	case "page":
		b.WriteString("        private int page = 1;\n")
	case "offset":
		b.WriteString("        private int offset = 0;\n")
	default:
		b.WriteString("        private String cursor;\n")
	}
	fmt.Fprintf(b, "        private %s(%s req) { this.req = req != null ? req : new %s(); }\n\n", iterClass, reqClass, reqClass)

	// fetch advances state and stores the next page in `pending`.
	b.WriteString("        private void fetch() {\n")
	b.WriteString("            if (done || pending != null) { return; }\n")
	if canAdvance {
		switch pg.Style {
		case "page":
			fmt.Fprintf(b, "            req.%s = page;\n", paramField)
		case "offset":
			fmt.Fprintf(b, "            req.%s = offset;\n", paramField)
		default:
			fmt.Fprintf(b, "            req.%s = cursor;\n", paramField)
		}
	}
	fmt.Fprintf(b, "            String resp = %s(req);\n", method)
	b.WriteString("            int n = pageCount(resp);\n")
	b.WriteString("            if (n == 0) { done = true; return; }\n")
	b.WriteString("            pending = resp;\n")
	if !canAdvance {
		b.WriteString("            done = true;\n")
		b.WriteString("        }\n\n")
	} else {
		switch pg.Style {
		case "page":
			b.WriteString("            page++;\n")
		case "offset":
			b.WriteString("            offset += n;\n")
		default:
			fmt.Fprintf(b, "            String next = pageString(resp, %s);\n", javaStr(nextField))
			b.WriteString("            if (next == null || next.isEmpty()) { done = true; } else { cursor = next; }\n")
		}
		b.WriteString("        }\n\n")
	}

	b.WriteString("        @Override public boolean hasNext() { fetch(); return pending != null; }\n\n")
	b.WriteString("        @Override public String next() {\n")
	b.WriteString("            fetch();\n")
	b.WriteString("            if (pending == null) { throw new java.util.NoSuchElementException(); }\n")
	b.WriteString("            String p = pending; pending = null; return p;\n")
	b.WriteString("        }\n")
	b.WriteString("    }\n\n")
}

func writeJavaPageHelpers(b *strings.Builder) {
	b.WriteString("    /** Item count of a paginated response (top-level array, else data/items/results array, else 1/0). */\n")
	b.WriteString("    private static int pageCount(String raw) {\n")
	b.WriteString("        Object v = Json.parse(raw);\n")
	b.WriteString("        if (v instanceof java.util.List) { return ((java.util.List<?>) v).size(); }\n")
	b.WriteString("        if (v instanceof Map) {\n")
	b.WriteString("            @SuppressWarnings(\"unchecked\") Map<String, Object> m = (Map<String, Object>) v;\n")
	b.WriteString("            for (String k : new String[]{\"data\", \"items\", \"results\"}) {\n")
	b.WriteString("                Object inner = m.get(k);\n")
	b.WriteString("                if (inner instanceof java.util.List) { return ((java.util.List<?>) inner).size(); }\n")
	b.WriteString("            }\n")
	b.WriteString("            return m.isEmpty() ? 0 : 1;\n")
	b.WriteString("        }\n")
	b.WriteString("        return v == null ? 0 : 1;\n")
	b.WriteString("    }\n\n")
	b.WriteString("    /** Extract a top-level string field (e.g. the next cursor); null if absent. */\n")
	b.WriteString("    private static String pageString(String raw, String field) {\n")
	b.WriteString("        Object v = Json.parse(raw);\n")
	b.WriteString("        if (v instanceof Map) {\n")
	b.WriteString("            Object f = ((Map<?, ?>) v).get(field);\n")
	b.WriteString("            if (f instanceof String) { return (String) f; }\n")
	b.WriteString("        }\n")
	b.WriteString("        return null;\n")
	b.WriteString("    }\n\n")
}

// javaModel emits a single model class for a named schema. Object schemas become
// classes with public fields ($ref fields typed to the referenced model class);
// non-object named schemas degrade to a class wrapping a raw JSON value.
func javaModel(api *ir.API, name string) string {
	s := api.Schemas[name]
	cls := javaClassName(name)

	var b strings.Builder
	fmt.Fprintf(&b, "package %s.model;\n\n", basePackage)
	b.WriteString("import java.util.List;\n")
	b.WriteString("import java.util.Map;\n\n")

	if d := oneLine(descOf(s)); d != "" {
		fmt.Fprintf(&b, "/** %s */\n", javaDoc(d))
	} else {
		fmt.Fprintf(&b, "/** Model for the %q schema. */\n", name)
	}
	fmt.Fprintf(&b, "public final class %s {\n", cls)

	if s == nil || (s.Type != "object" && len(s.Properties) == 0) {
		// Non-object: wrap the raw value.
		fmt.Fprintf(&b, "    /** Raw value for the non-object %q schema. */\n", name)
		fmt.Fprintf(&b, "    public %s value;\n", boxedType(javaTypeForSchema(s)))
		b.WriteString("}\n")
		return b.String()
	}

	required := map[string]bool{}
	for _, r := range s.Required {
		required[r] = true
	}
	seen := map[string]bool{}
	for _, pn := range sortedKeys(s.Properties) {
		fld := javaFieldName(pn)
		if fld == "" || seen[fld] {
			continue
		}
		seen[fld] = true
		ps := s.Properties[pn]
		if d := oneLine(descOf(ps)); d != "" {
			fmt.Fprintf(&b, "    /** %s */\n", javaDoc(d))
		} else if required[pn] {
			b.WriteString("    /** Required. */\n")
		}
		fmt.Fprintf(&b, "    public %s %s;\n", boxedType(javaRefType(api, ps)), fld)
	}
	b.WriteString("}\n")
	return b.String()
}

// javaJSON emits a tiny dependency-free JSON encoder/parser used by the client
// for request bodies and pagination inspection.
func javaJSON() string {
	var b strings.Builder
	fmt.Fprintf(&b, "package %s;\n\n", basePackage)
	b.WriteString("import java.util.ArrayList;\n")
	b.WriteString("import java.util.LinkedHashMap;\n")
	b.WriteString("import java.util.List;\n")
	b.WriteString("import java.util.Map;\n\n")
	b.WriteString("/** Minimal dependency-free JSON encoder + parser (objects, arrays, scalars). */\n")
	b.WriteString("final class Json {\n")
	b.WriteString("    private Json() {}\n\n")

	// encode
	b.WriteString("    static String encode(Object v) {\n")
	b.WriteString("        StringBuilder sb = new StringBuilder();\n")
	b.WriteString("        write(sb, v);\n")
	b.WriteString("        return sb.toString();\n")
	b.WriteString("    }\n\n")
	b.WriteString("    private static void write(StringBuilder sb, Object v) {\n")
	b.WriteString("        if (v == null) { sb.append(\"null\"); return; }\n")
	b.WriteString("        if (v instanceof String) { writeString(sb, (String) v); return; }\n")
	b.WriteString("        if (v instanceof Boolean || v instanceof Number) { sb.append(v.toString()); return; }\n")
	b.WriteString("        if (v instanceof Map) {\n")
	b.WriteString("            sb.append('{'); boolean first = true;\n")
	b.WriteString("            for (Map.Entry<?, ?> e : ((Map<?, ?>) v).entrySet()) {\n")
	b.WriteString("                if (!first) { sb.append(','); } first = false;\n")
	b.WriteString("                writeString(sb, String.valueOf(e.getKey())); sb.append(':'); write(sb, e.getValue());\n")
	b.WriteString("            }\n")
	b.WriteString("            sb.append('}'); return;\n")
	b.WriteString("        }\n")
	b.WriteString("        if (v instanceof Iterable) {\n")
	b.WriteString("            sb.append('['); boolean first = true;\n")
	b.WriteString("            for (Object o : (Iterable<?>) v) {\n")
	b.WriteString("                if (!first) { sb.append(','); } first = false; write(sb, o);\n")
	b.WriteString("            }\n")
	b.WriteString("            sb.append(']'); return;\n")
	b.WriteString("        }\n")
	b.WriteString("        writeString(sb, v.toString());\n")
	b.WriteString("    }\n\n")
	b.WriteString("    private static void writeString(StringBuilder sb, String s) {\n")
	b.WriteString("        sb.append('\"');\n")
	b.WriteString("        for (int i = 0; i < s.length(); i++) {\n")
	b.WriteString("            char c = s.charAt(i);\n")
	b.WriteString("            switch (c) {\n")
	b.WriteString("                case '\"': sb.append(\"\\\\\\\"\"); break;\n")
	b.WriteString("                case '\\\\': sb.append(\"\\\\\\\\\"); break;\n")
	b.WriteString("                case '\\n': sb.append(\"\\\\n\"); break;\n")
	b.WriteString("                case '\\r': sb.append(\"\\\\r\"); break;\n")
	b.WriteString("                case '\\t': sb.append(\"\\\\t\"); break;\n")
	b.WriteString("                default:\n")
	b.WriteString("                    if (c < 0x20) { sb.append(String.format(\"\\\\u%04x\", (int) c)); } else { sb.append(c); }\n")
	b.WriteString("            }\n")
	b.WriteString("        }\n")
	b.WriteString("        sb.append('\"');\n")
	b.WriteString("    }\n\n")

	// parse
	b.WriteString("    static Object parse(String s) {\n")
	b.WriteString("        if (s == null) { return null; }\n")
	b.WriteString("        try { return new Parser(s).parseValue(); } catch (RuntimeException ex) { return null; }\n")
	b.WriteString("    }\n\n")
	b.WriteString("    private static final class Parser {\n")
	b.WriteString("        private final String s; private int i;\n")
	b.WriteString("        Parser(String s) { this.s = s; }\n")
	b.WriteString("        Object parseValue() {\n")
	b.WriteString("            skipWs();\n")
	b.WriteString("            if (i >= s.length()) { return null; }\n")
	b.WriteString("            char c = s.charAt(i);\n")
	b.WriteString("            if (c == '{') { return parseObject(); }\n")
	b.WriteString("            if (c == '[') { return parseArray(); }\n")
	b.WriteString("            if (c == '\"') { return parseString(); }\n")
	b.WriteString("            if (c == 't' || c == 'f') { return parseBool(); }\n")
	b.WriteString("            if (c == 'n') { i += 4; return null; }\n")
	b.WriteString("            return parseNumber();\n")
	b.WriteString("        }\n")
	b.WriteString("        private Map<String, Object> parseObject() {\n")
	b.WriteString("            Map<String, Object> m = new LinkedHashMap<>(); i++; skipWs();\n")
	b.WriteString("            if (peek() == '}') { i++; return m; }\n")
	b.WriteString("            while (true) {\n")
	b.WriteString("                skipWs(); String k = parseString(); skipWs(); i++; /* ':' */\n")
	b.WriteString("                m.put(k, parseValue()); skipWs();\n")
	b.WriteString("                char c = peek(); i++;\n")
	b.WriteString("                if (c == '}') { break; }\n")
	b.WriteString("            }\n")
	b.WriteString("            return m;\n")
	b.WriteString("        }\n")
	b.WriteString("        private List<Object> parseArray() {\n")
	b.WriteString("            List<Object> a = new ArrayList<>(); i++; skipWs();\n")
	b.WriteString("            if (peek() == ']') { i++; return a; }\n")
	b.WriteString("            while (true) {\n")
	b.WriteString("                a.add(parseValue()); skipWs(); char c = peek(); i++;\n")
	b.WriteString("                if (c == ']') { break; }\n")
	b.WriteString("            }\n")
	b.WriteString("            return a;\n")
	b.WriteString("        }\n")
	b.WriteString("        private String parseString() {\n")
	b.WriteString("            StringBuilder sb = new StringBuilder(); i++; /* opening quote */\n")
	b.WriteString("            while (i < s.length()) {\n")
	b.WriteString("                char c = s.charAt(i++);\n")
	b.WriteString("                if (c == '\"') { break; }\n")
	b.WriteString("                if (c == '\\\\' && i < s.length()) {\n")
	b.WriteString("                    char e = s.charAt(i++);\n")
	b.WriteString("                    switch (e) {\n")
	b.WriteString("                        case 'n': sb.append('\\n'); break;\n")
	b.WriteString("                        case 't': sb.append('\\t'); break;\n")
	b.WriteString("                        case 'r': sb.append('\\r'); break;\n")
	b.WriteString("                        case 'u': sb.append((char) Integer.parseInt(s.substring(i, i + 4), 16)); i += 4; break;\n")
	b.WriteString("                        default: sb.append(e);\n")
	b.WriteString("                    }\n")
	b.WriteString("                } else { sb.append(c); }\n")
	b.WriteString("            }\n")
	b.WriteString("            return sb.toString();\n")
	b.WriteString("        }\n")
	b.WriteString("        private Boolean parseBool() {\n")
	b.WriteString("            if (s.charAt(i) == 't') { i += 4; return Boolean.TRUE; }\n")
	b.WriteString("            i += 5; return Boolean.FALSE;\n")
	b.WriteString("        }\n")
	b.WriteString("        private Object parseNumber() {\n")
	b.WriteString("            int start = i;\n")
	b.WriteString("            while (i < s.length() && \"+-0123456789.eE\".indexOf(s.charAt(i)) >= 0) { i++; }\n")
	b.WriteString("            String num = s.substring(start, i);\n")
	b.WriteString("            try { if (num.contains(\".\") || num.contains(\"e\") || num.contains(\"E\")) { return Double.parseDouble(num); } return Long.parseLong(num); }\n")
	b.WriteString("            catch (NumberFormatException ex) { return num; }\n")
	b.WriteString("        }\n")
	b.WriteString("        private char peek() { return i < s.length() ? s.charAt(i) : ' '; }\n")
	b.WriteString("        private void skipWs() { while (i < s.length() && Character.isWhitespace(s.charAt(i))) { i++; } }\n")
	b.WriteString("    }\n")
	b.WriteString("}\n")
	return b.String()
}

// ---- body fields ----

type javaBodyField struct {
	name   string
	schema *ir.Schema
}

func javaBodyFields(api *ir.API, op ir.Operation) []javaBodyField {
	if op.RequestBody == nil {
		return nil
	}
	body := api.Resolve(op.RequestBody)
	if body == nil {
		return nil
	}
	if body.Type == "object" || len(body.Properties) > 0 {
		out := make([]javaBodyField, 0, len(body.Properties))
		for _, n := range sortedKeys(body.Properties) {
			out = append(out, javaBodyField{name: n, schema: body.Properties[n]})
		}
		return out
	}
	return []javaBodyField{{name: "body", schema: body}}
}

func splitParams(op ir.Operation) (path, query, header []ir.Param) {
	for _, p := range op.Params {
		switch p.In {
		case "path":
			path = append(path, p)
		case "query":
			query = append(query, p)
		case "header":
			header = append(header, p)
		}
	}
	return path, query, header
}

// ---- type mapping ----

// javaType maps a scalar/array param schema to a Java type (primitives allowed).
func javaType(s *ir.Schema) string {
	if s == nil {
		return "String"
	}
	switch s.Type {
	case "integer":
		return "long"
	case "number":
		return "double"
	case "boolean":
		return "boolean"
	case "array":
		return "java.util.List<" + boxedType(javaType(s.Items)) + ">"
	case "object":
		return "java.util.Map<String, Object>"
	case "string":
		return "String"
	}
	if len(s.Properties) > 0 {
		return "java.util.Map<String, Object>"
	}
	return "String"
}

func javaTypeForSchema(s *ir.Schema) string { return javaType(s) }

// javaRefType resolves a $ref to the model class (fully qualified) so model and
// body fields reference generated types; otherwise falls back to javaType.
func javaRefType(api *ir.API, s *ir.Schema) string {
	if s == nil {
		return "Object"
	}
	if s.Ref != "" {
		if api != nil {
			if named, ok := api.Schemas[s.Ref]; ok && named != nil {
				if cn := javaClassName(s.Ref); cn != "" {
					return basePackage + ".model." + cn
				}
			}
		}
		return "java.util.Map<String, Object>"
	}
	if s.Type == "array" {
		return "java.util.List<" + boxedType(javaRefType(api, s.Items)) + ">"
	}
	return javaType(s)
}

// boxedType converts a Java primitive to its wrapper class (so it can be a
// nullable field / generic type argument); non-primitives pass through.
func boxedType(t string) string {
	switch t {
	case "long":
		return "Long"
	case "double":
		return "Double"
	case "boolean":
		return "Boolean"
	case "int":
		return "Integer"
	}
	return t
}

func descOf(s *ir.Schema) string {
	if s == nil {
		return ""
	}
	return s.Description
}

// ---- naming ----

// javaClassName converts an identifier into a PascalCase class name.
func javaClassName(s string) string {
	parts := splitIdent(s)
	var b strings.Builder
	for _, p := range parts {
		r := []rune(p)
		if r[0] >= 'a' && r[0] <= 'z' {
			r[0] -= 32
		}
		b.WriteString(string(r))
	}
	out := b.String()
	if out == "" {
		return "Model"
	}
	if out[0] >= '0' && out[0] <= '9' {
		out = "M" + out
	}
	return out
}

// javaMethodName converts an operation ID into a camelCase method name.
func javaMethodName(s string) string {
	cls := javaClassName(s)
	if cls == "" {
		return "call"
	}
	r := []rune(cls)
	if r[0] >= 'A' && r[0] <= 'Z' {
		r[0] += 32
	}
	name := string(r)
	if javaKeywords[name] {
		name += "_"
	}
	return name
}

// javaFieldName converts a property/param name into a camelCase field name.
func javaFieldName(s string) string {
	name := javaMethodName(s)
	if name == "" {
		return "field"
	}
	return name
}

// splitIdent splits an identifier into words on non-alphanumeric runs and
// camelCase boundaries.
func splitIdent(s string) []string {
	var words []string
	var cur strings.Builder
	flush := func() {
		if cur.Len() > 0 {
			words = append(words, cur.String())
			cur.Reset()
		}
	}
	var prevLower bool
	for _, r := range s {
		switch {
		case r >= 'A' && r <= 'Z':
			if prevLower {
				flush()
			}
			cur.WriteRune(r)
			prevLower = false
		case r >= 'a' && r <= 'z' || r >= '0' && r <= '9':
			cur.WriteRune(r)
			prevLower = r >= 'a' && r <= 'z'
		default:
			flush()
			prevLower = false
		}
	}
	flush()
	return words
}

