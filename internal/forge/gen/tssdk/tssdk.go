// Package tssdk is a Forge generator that emits a TypeScript client SDK
// (client.ts + package.json + README.md) for an API described by the IR. The
// generated client uses the global fetch and has zero runtime dependencies.
// Output is deterministic: operations are walked via api.SortedOperations() and
// all map keys are sorted before emission. The emitted TS is string data and is
// not type-checked by this generator; only this Go file must build and be
// gofmt-clean.
package tssdk

import (
	"fmt"
	"sort"
	"strings"

	"github.com/rysh-ai/rysh-cli-code/internal/forge/gen"
	"github.com/rysh-ai/rysh-cli-code/internal/forge/ir"
)

func init() { gen.Register(&generator{}) }

type generator struct{}

func (g *generator) Name() string { return "ts-sdk" }

// Generate renders the API into a TypeScript SDK FileSet.
func (g *generator) Generate(api *ir.API, opts gen.Options) (*gen.FileSet, error) {
	fs := gen.NewFileSet()

	pkgName := opts.PackageName
	if pkgName == "" {
		pkgName = ir.Slugify(api.Name)
	}
	if pkgName == "" {
		pkgName = "api-client"
	}

	fs.AddString("client.ts", tsClient(api))
	fs.AddString("package.json", tsPackageJSON(pkgName, api))
	fs.AddString("README.md", tsReadme(pkgName, api))
	return fs, nil
}

func tsPackageJSON(name string, api *ir.API) string {
	version := api.Version
	if strings.TrimSpace(version) == "" {
		version = "0.1.0"
	}
	var b strings.Builder
	b.WriteString("{\n")
	fmt.Fprintf(&b, "  \"name\": %s,\n", jsonString(name))
	fmt.Fprintf(&b, "  \"version\": %s,\n", jsonString(version))
	fmt.Fprintf(&b, "  \"description\": %s,\n", jsonString(oneLine(api.Description)))
	b.WriteString("  \"type\": \"module\",\n")
	b.WriteString("  \"main\": \"client.ts\",\n")
	b.WriteString("  \"types\": \"client.ts\",\n")
	b.WriteString("  \"license\": \"MIT\"\n")
	b.WriteString("}\n")
	return b.String()
}

func tsReadme(name string, api *ir.API) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# %s\n\n", name)
	if d := oneLine(api.Description); d != "" {
		fmt.Fprintf(&b, "%s\n\n", d)
	}
	b.WriteString("Generated by Forge (ts-sdk).\n\n")
	b.WriteString("```ts\n")
	b.WriteString("import { Client } from \"./client\";\n\n")
	fmt.Fprintf(&b, "const client = new Client({ baseUrl: %s, apiKey: process.env.API_KEY });\n", jsonString(api.BaseURL()))
	ops := api.SortedOperations()
	if len(ops) > 0 {
		fmt.Fprintf(&b, "const result = await client.%s({});\n", tsMethodName(ops[0].ID))
	}
	b.WriteString("```\n")
	return b.String()
}

func tsClient(api *ir.API) string {
	var b strings.Builder

	fmt.Fprintf(&b, "// Generated TypeScript client for %s.\n", oneLine(firstNonEmpty(api.Name, "the API")))
	if d := oneLine(api.Description); d != "" {
		fmt.Fprintf(&b, "// %s\n", d)
	}
	b.WriteString("// Generated by Forge (ts-sdk). Do not edit by hand.\n\n")

	b.WriteString("export interface ClientOptions {\n")
	b.WriteString("  baseUrl?: string;\n")
	b.WriteString("  apiKey?: string;\n")
	b.WriteString("  username?: string;\n")
	b.WriteString("  password?: string;\n")
	b.WriteString("  fetch?: typeof fetch;\n")
	b.WriteString("}\n\n")

	fmt.Fprintf(&b, "const DEFAULT_BASE_URL = %s;\n\n", jsonString(api.BaseURL()))

	// Exported model interfaces for every named component schema (module scope).
	writeTSModels(&b, api)

	// Param interfaces are declared at module scope (they cannot live inside the
	// class body); methods (and pagination generators) are collected separately
	// and emitted inside the class body.
	var ifaces, methods strings.Builder
	for _, op := range api.SortedOperations() {
		writeTSMethod(&ifaces, &methods, api, op)
	}
	for _, op := range api.SortedOperations() {
		if op.Pagination != nil {
			writeTSPaginator(&methods, api, op)
		}
	}
	b.WriteString(ifaces.String())

	b.WriteString("export class Client {\n")
	b.WriteString("  private baseUrl: string;\n")
	b.WriteString("  private apiKey?: string;\n")
	b.WriteString("  private username?: string;\n")
	b.WriteString("  private password?: string;\n")
	b.WriteString("  private fetchImpl: typeof fetch;\n\n")

	b.WriteString("  constructor(opts: ClientOptions = {}) {\n")
	b.WriteString("    this.baseUrl = (opts.baseUrl ?? DEFAULT_BASE_URL).replace(/\\/+$/, \"\");\n")
	b.WriteString("    this.apiKey = opts.apiKey;\n")
	b.WriteString("    this.username = opts.username;\n")
	b.WriteString("    this.password = opts.password;\n")
	b.WriteString("    this.fetchImpl = opts.fetch ?? fetch;\n")
	b.WriteString("  }\n\n")

	writeTSAuth(&b, api)
	writeTSRequest(&b)

	b.WriteString(methods.String())

	b.WriteString("}\n")

	// Module-scope helpers backing the pagination generators (emitted only when
	// at least one paginated operation exists).
	for _, op := range api.SortedOperations() {
		if op.Pagination != nil {
			writeTSPageHelpers(&b)
			break
		}
	}
	return b.String()
}

// writeTSPageHelpers emits the generic JSON inspection helpers used by the
// pagination generators.
func writeTSPageHelpers(b *strings.Builder) {
	b.WriteString("\n// tsPageCount returns the number of items in a paginated response: a top-level\n")
	b.WriteString("// array's length, else a data/items/results array's length, else 1 for a\n")
	b.WriteString("// non-empty object and 0 for empty input.\n")
	b.WriteString("function tsPageCount(v: any): number {\n")
	b.WriteString("  if (Array.isArray(v)) return v.length;\n")
	b.WriteString("  if (v && typeof v === \"object\") {\n")
	b.WriteString("    for (const k of [\"data\", \"items\", \"results\"]) {\n")
	b.WriteString("      if (Array.isArray(v[k])) return v[k].length;\n")
	b.WriteString("    }\n")
	b.WriteString("    return Object.keys(v).length === 0 ? 0 : 1;\n")
	b.WriteString("  }\n")
	b.WriteString("  return v == null ? 0 : 1;\n")
	b.WriteString("}\n\n")

	b.WriteString("// tsPageString extracts a top-level string field (e.g. the next cursor),\n")
	b.WriteString("// returning \"\" when absent or not a string.\n")
	b.WriteString("function tsPageString(v: any, field: string): string {\n")
	b.WriteString("  if (v && typeof v === \"object\" && typeof v[field] === \"string\") return v[field];\n")
	b.WriteString("  return \"\";\n")
	b.WriteString("}\n")
}

func writeTSAuth(b *strings.Builder, api *ir.API) {
	b.WriteString("  private applyAuth(headers: Record<string, string>, query: URLSearchParams): void {\n")
	for _, scheme := range api.Auth {
		switch scheme.Type {
		case "apiKey":
			switch scheme.In {
			case "header":
				fmt.Fprintf(b, "    if (this.apiKey) headers[%s] = this.apiKey;\n", jsonString(scheme.KeyName))
			case "query":
				fmt.Fprintf(b, "    if (this.apiKey) query.set(%s, this.apiKey);\n", jsonString(scheme.KeyName))
			}
		case "http":
			switch strings.ToLower(scheme.Scheme) {
			case "bearer":
				b.WriteString("    if (this.apiKey) headers[\"Authorization\"] = `Bearer ${this.apiKey}`;\n")
			case "basic":
				b.WriteString("    if (this.username) headers[\"Authorization\"] = `Basic ${btoa(`${this.username}:${this.password ?? \"\"}`)}`;\n")
			}
		case "oauth2":
			b.WriteString("    if (this.apiKey) headers[\"Authorization\"] = `Bearer ${this.apiKey}`;\n")
		}
	}
	b.WriteString("  }\n\n")
}

func writeTSRequest(b *strings.Builder) {
	b.WriteString("  private async request(\n")
	b.WriteString("    method: string,\n")
	b.WriteString("    path: string,\n")
	b.WriteString("    query: URLSearchParams,\n")
	b.WriteString("    headers: Record<string, string>,\n")
	b.WriteString("    body?: unknown,\n")
	b.WriteString("  ): Promise<any> {\n")
	b.WriteString("    this.applyAuth(headers, query);\n")
	b.WriteString("    const qs = query.toString();\n")
	b.WriteString("    const url = this.baseUrl + path + (qs ? `?${qs}` : \"\");\n")
	b.WriteString("    headers[\"Accept\"] = \"application/json\";\n")
	b.WriteString("    const init: RequestInit = { method, headers };\n")
	b.WriteString("    if (body !== undefined) {\n")
	b.WriteString("      headers[\"Content-Type\"] = \"application/json\";\n")
	b.WriteString("      init.body = JSON.stringify(body);\n")
	b.WriteString("    }\n")
	b.WriteString("    const resp = await this.fetchImpl(url, init);\n")
	b.WriteString("    const text = await resp.text();\n")
	b.WriteString("    if (!resp.ok) {\n")
	b.WriteString("      throw new Error(`${method} ${path} -> HTTP ${resp.status}: ${text}`);\n")
	b.WriteString("    }\n")
	b.WriteString("    return text ? JSON.parse(text) : null;\n")
	b.WriteString("  }\n\n")
}

// writeTSMethod renders one operation. The param interface is written to iface
// (module scope); the async method is written to b (class-body scope).
func writeTSMethod(iface, b *strings.Builder, api *ir.API, op ir.Operation) {
	name := tsMethodName(op.ID)
	paramsType := tsTypeName(op.ID) + "Params"

	pathParams, queryParams, headerParams := splitParams(op)
	bodyFields := tsBodyFields(api, op)

	// Params interface (module scope).
	fmt.Fprintf(iface, "export interface %s {\n", paramsType)
	seen := map[string]bool{}
	emitProp := func(name string, schema *ir.Schema, required bool, desc string) {
		if seen[name] {
			return
		}
		seen[name] = true
		if d := oneLine(desc); d != "" {
			fmt.Fprintf(iface, "  /** %s */\n", d)
		}
		opt := "?"
		if required {
			opt = ""
		}
		fmt.Fprintf(iface, "  %s%s: %s;\n", tsPropKey(name), opt, tsRefType(api, schema))
	}
	for _, p := range pathParams {
		emitProp(p.Name, p.Schema, p.Required, p.Description)
	}
	for _, p := range append(queryParams, headerParams...) {
		emitProp(p.Name, p.Schema, p.Required, p.Description)
	}
	for _, f := range bodyFields {
		emitProp(f.name, f.schema, false, f.desc)
	}
	iface.WriteString("}\n\n")

	// Method.
	if summary := oneLine(firstNonEmpty(op.Summary, op.Description)); summary != "" {
		fmt.Fprintf(b, "  /** %s (%s %s) */\n", summary, op.Method, op.Path)
	} else {
		fmt.Fprintf(b, "  /** %s %s */\n", op.Method, op.Path)
	}
	fmt.Fprintf(b, "  async %s(params: %s = {} as %s): Promise<any> {\n", name, paramsType, paramsType)

	// Path.
	fmt.Fprintf(b, "    let path = %s;\n", jsonString(op.Path))
	for _, p := range pathParams {
		fmt.Fprintf(b, "    path = path.replace(%s, encodeURIComponent(String(params[%s])));\n",
			jsonString("{"+p.Name+"}"), jsonString(p.Name))
	}

	// Query.
	b.WriteString("    const query = new URLSearchParams();\n")
	for _, p := range queryParams {
		fmt.Fprintf(b, "    if (params[%s] !== undefined) query.set(%s, String(params[%s]));\n",
			jsonString(p.Name), jsonString(p.Name), jsonString(p.Name))
	}

	// Headers.
	b.WriteString("    const headers: Record<string, string> = {};\n")
	for _, p := range headerParams {
		fmt.Fprintf(b, "    if (params[%s] !== undefined) headers[%s] = String(params[%s]);\n",
			jsonString(p.Name), jsonString(p.Name), jsonString(p.Name))
	}

	// Body.
	if op.Mutating && len(bodyFields) > 0 {
		b.WriteString("    const body: Record<string, unknown> = {};\n")
		for _, f := range bodyFields {
			fmt.Fprintf(b, "    if (params[%s] !== undefined) body[%s] = params[%s];\n",
				jsonString(f.name), jsonString(f.name), jsonString(f.name))
		}
		fmt.Fprintf(b, "    return this.request(%s, path, query, headers, body);\n", jsonString(op.Method))
	} else if op.Mutating {
		fmt.Fprintf(b, "    return this.request(%s, path, query, headers, {});\n", jsonString(op.Method))
	} else {
		fmt.Fprintf(b, "    return this.request(%s, path, query, headers);\n", jsonString(op.Method))
	}
	b.WriteString("  }\n\n")
}

// writeTSModels emits an exported interface (object schemas) or type alias
// (everything else) for each named component schema, in sorted order. $ref
// properties resolve to the named interface so models reference each other.
func writeTSModels(b *strings.Builder, api *ir.API) {
	names := make([]string, 0, len(api.Schemas))
	for n := range api.Schemas {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, name := range names {
		s := api.Schemas[name]
		typeName := tsTypeName(name)
		if typeName == "" {
			continue
		}
		if d := oneLine(descOf(s)); d != "" {
			fmt.Fprintf(b, "/** %s */\n", d)
		}
		if s == nil || (s.Type != "object" && len(s.Properties) == 0) {
			fmt.Fprintf(b, "export type %s = %s;\n\n", typeName, tsRefType(api, s))
			continue
		}
		required := map[string]bool{}
		for _, r := range s.Required {
			required[r] = true
		}
		fmt.Fprintf(b, "export interface %s {\n", typeName)
		propNames := make([]string, 0, len(s.Properties))
		for pn := range s.Properties {
			propNames = append(propNames, pn)
		}
		sort.Strings(propNames)
		for _, pn := range propNames {
			if d := oneLine(descOf(s.Properties[pn])); d != "" {
				fmt.Fprintf(b, "  /** %s */\n", d)
			}
			opt := "?"
			if required[pn] {
				opt = ""
			}
			fmt.Fprintf(b, "  %s%s: %s;\n", tsPropKey(pn), opt, tsRefType(api, s.Properties[pn]))
		}
		b.WriteString("}\n\n")
	}
}

// writeTSPaginator emits an async generator method that yields each page of a
// paginated operation (best-effort; see the Go SDK for the full heuristic). The
// generator advances the paging param on the params object and stops when a page
// is empty, so it can never loop forever.
func writeTSPaginator(b *strings.Builder, api *ir.API, op ir.Operation) {
	method := tsMethodName(op.ID)
	paramsType := tsTypeName(op.ID) + "Params"
	pg := op.Pagination

	pageParam := pg.Param
	if pageParam == "" {
		switch pg.Style {
		case "page":
			pageParam = "page"
		case "offset":
			pageParam = "offset"
		default:
			pageParam = "cursor"
		}
	}
	nextField := pg.NextField
	if nextField == "" {
		nextField = "next_cursor"
	}
	canAdvance := false
	for _, p := range op.Params {
		if p.Name == pageParam {
			canAdvance = true
			break
		}
	}

	fmt.Fprintf(b, "  /** Iterate every page of %s (style %q, param %q). */\n", method, pg.Style, pageParam)
	fmt.Fprintf(b, "  async *%sAll(params: %s = {} as %s): AsyncGenerator<any, void, unknown> {\n", method, paramsType, paramsType)
	b.WriteString("    const p: Record<string, any> = { ...params };\n")
	switch pg.Style {
	case "page":
		b.WriteString("    let page = 1;\n")
	case "offset":
		b.WriteString("    let offset = 0;\n")
	default:
		b.WriteString("    let cursor: string | undefined = undefined;\n")
	}
	b.WriteString("    for (;;) {\n")
	if canAdvance {
		switch pg.Style {
		case "page":
			fmt.Fprintf(b, "      p[%s] = page;\n", jsonString(pageParam))
		case "offset":
			fmt.Fprintf(b, "      p[%s] = offset;\n", jsonString(pageParam))
		default:
			fmt.Fprintf(b, "      if (cursor !== undefined) p[%s] = cursor;\n", jsonString(pageParam))
		}
	}
	fmt.Fprintf(b, "      const result = await this.%s(p as %s);\n", method, paramsType)
	b.WriteString("      const n = tsPageCount(result);\n")
	b.WriteString("      if (n === 0) return;\n")
	b.WriteString("      yield result;\n")
	if !canAdvance {
		b.WriteString("      return;\n")
	} else {
		switch pg.Style {
		case "page":
			b.WriteString("      page += 1;\n")
		case "offset":
			b.WriteString("      offset += n;\n")
		default:
			fmt.Fprintf(b, "      const next = tsPageString(result, %s);\n", jsonString(nextField))
			b.WriteString("      if (!next) return;\n")
			b.WriteString("      cursor = next;\n")
		}
	}
	b.WriteString("    }\n")
	b.WriteString("  }\n\n")
}

// tsBodyField is one synthetic request-body field.
type tsBodyField struct {
	name   string
	schema *ir.Schema
	desc   string
}

func tsBodyFields(api *ir.API, op ir.Operation) []tsBodyField {
	if op.RequestBody == nil {
		return nil
	}
	body := api.Resolve(op.RequestBody)
	if body == nil {
		return nil
	}
	if body.Type == "object" || len(body.Properties) > 0 {
		names := make([]string, 0, len(body.Properties))
		for n := range body.Properties {
			names = append(names, n)
		}
		sort.Strings(names)
		out := make([]tsBodyField, 0, len(names))
		for _, n := range names {
			ps := body.Properties[n]
			out = append(out, tsBodyField{name: n, schema: ps, desc: descOf(ps)})
		}
		return out
	}
	return []tsBodyField{{name: "body", schema: body, desc: descOf(body)}}
}

func splitParams(op ir.Operation) (path, query, header []ir.Param) {
	for _, p := range op.Params {
		switch p.In {
		case "path":
			path = append(path, p)
		case "query":
			query = append(query, p)
		case "header":
			header = append(header, p)
		}
	}
	return path, query, header
}

// tsRefType is like tsType but resolves a $ref to the exported interface name
// of the generated model, so models reference each other by name. Unknown refs
// degrade to Record<string, unknown>. Used for model and body fields; params
// keep tsType (params are scalars).
func tsRefType(api *ir.API, s *ir.Schema) string {
	if s == nil {
		return "unknown"
	}
	if s.Ref != "" {
		if api != nil {
			if named, ok := api.Schemas[s.Ref]; ok && named != nil {
				if tn := tsTypeName(s.Ref); tn != "" {
					return tn
				}
			}
		}
		return "Record<string, unknown>"
	}
	switch s.Type {
	case "integer", "number":
		return "number"
	case "boolean":
		return "boolean"
	case "array":
		return tsRefType(api, s.Items) + "[]"
	case "string":
		return "string"
	case "object":
		return "Record<string, unknown>"
	}
	if len(s.Properties) > 0 {
		return "Record<string, unknown>"
	}
	return "string"
}

func descOf(s *ir.Schema) string {
	if s == nil {
		return ""
	}
	return s.Description
}

// tsMethodName converts an operation ID into a lowerCamelCase method name.
func tsMethodName(s string) string {
	n := camel(s)
	if n == "" {
		return "call"
	}
	r := []rune(n)
	r[0] = lower(r[0])
	return string(r)
}

// tsTypeName converts an operation ID into an UpperCamelCase type name.
func tsTypeName(s string) string {
	n := camel(s)
	if n == "" {
		return "Op"
	}
	return n
}

// tsPropKey quotes a property key when it is not a plain identifier.
func tsPropKey(s string) string {
	plain := s != ""
	for i, r := range s {
		isAlpha := r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r == '_' || r == '$'
		isDigit := r >= '0' && r <= '9'
		if i == 0 && !isAlpha {
			plain = false
			break
		}
		if !isAlpha && !isDigit {
			plain = false
			break
		}
	}
	if plain {
		return s
	}
	return jsonString(s)
}

// camel splits on non-alphanumeric runes and upper-cases each word's first rune.
func camel(s string) string {
	var b strings.Builder
	upper := true
	for _, r := range s {
		switch {
		case r >= 'a' && r <= 'z':
			if upper {
				b.WriteRune(r - 32)
				upper = false
			} else {
				b.WriteRune(r)
			}
		case r >= 'A' && r <= 'Z':
			b.WriteRune(r)
			upper = false
		case r >= '0' && r <= '9':
			if b.Len() == 0 {
				b.WriteByte('X')
			}
			b.WriteRune(r)
			upper = false
		default:
			upper = true
		}
	}
	return b.String()
}

func lower(r rune) rune {
	if r >= 'A' && r <= 'Z' {
		return r + 32
	}
	return r
}

// jsonString renders s as a JSON/TS double-quoted string literal.
func jsonString(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch r {
		case '"':
			b.WriteString("\\\"")
		case '\\':
			b.WriteString("\\\\")
		case '\n':
			b.WriteString("\\n")
		case '\r':
			b.WriteString("\\r")
		case '\t':
			b.WriteString("\\t")
		default:
			b.WriteRune(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}

func oneLine(s string) string {
	s = strings.TrimSpace(s)
	if i := strings.IndexByte(s, '\n'); i >= 0 {
		s = strings.TrimSpace(s[:i])
	}
	if len(s) > 200 {
		s = s[:199] + "…"
	}
	return s
}

func firstNonEmpty(vals ...string) string {
	for _, v := range vals {
		if strings.TrimSpace(v) != "" {
			return v
		}
	}
	return ""
}
