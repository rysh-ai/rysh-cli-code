// Package pysdk is a Forge generator that emits a Python client SDK
// (client.py + pyproject.toml + README.md) for an API described by the IR. The
// generated client uses only the standard library (urllib.request) and has zero
// third-party dependencies. Output is deterministic: operations are walked via
// api.SortedOperations() and all map keys are sorted before emission. The
// emitted Python is string data and is not executed by this generator; only
// this Go file must build and be gofmt-clean.
package pysdk

import (
	"fmt"
	"sort"
	"strings"

	"github.com/rysh-ai/rysh-cli-code/internal/forge/gen"
	"github.com/rysh-ai/rysh-cli-code/internal/forge/ir"
)

func init() { gen.Register(&generator{}) }

type generator struct{}

func (g *generator) Name() string { return "py-sdk" }

// Generate renders the API into a Python SDK FileSet.
func (g *generator) Generate(api *ir.API, opts gen.Options) (*gen.FileSet, error) {
	fs := gen.NewFileSet()

	dist := opts.PackageName
	if dist == "" {
		dist = ir.Slugify(api.Name)
	}
	if dist == "" {
		dist = "api-client"
	}

	fs.AddString("client.py", pyClient(api))
	fs.AddString("pyproject.toml", pyProject(dist, api))
	fs.AddString("README.md", pyReadme(dist, api))
	return fs, nil
}

func pyProject(name string, api *ir.API) string {
	version := api.Version
	if strings.TrimSpace(version) == "" {
		version = "0.1.0"
	}
	var b strings.Builder
	b.WriteString("[build-system]\n")
	b.WriteString("requires = [\"setuptools>=61\"]\n")
	b.WriteString("build-backend = \"setuptools.build_meta\"\n\n")
	b.WriteString("[project]\n")
	fmt.Fprintf(&b, "name = %s\n", pyStr(name))
	fmt.Fprintf(&b, "version = %s\n", pyStr(version))
	fmt.Fprintf(&b, "description = %s\n", pyStr(oneLine(api.Description)))
	b.WriteString("requires-python = \">=3.8\"\n")
	b.WriteString("dependencies = []\n")
	return b.String()
}

func pyReadme(name string, api *ir.API) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# %s\n\n", name)
	if d := oneLine(api.Description); d != "" {
		fmt.Fprintf(&b, "%s\n\n", d)
	}
	b.WriteString("Generated by Forge (py-sdk). Standard-library only (urllib).\n\n")
	b.WriteString("```python\n")
	b.WriteString("from client import Client\n\n")
	fmt.Fprintf(&b, "client = Client(base_url=%s, api_key=\"...\")\n", pyStr(api.BaseURL()))
	ops := api.SortedOperations()
	if len(ops) > 0 {
		fmt.Fprintf(&b, "result = client.%s()\n", pyMethodName(ops[0].ID))
	}
	b.WriteString("```\n")
	return b.String()
}

func pyClient(api *ir.API) string {
	var b strings.Builder

	fmt.Fprintf(&b, "\"\"\"Generated Python client for %s.\n\n", oneLine(firstNonEmpty(api.Name, "the API")))
	if d := oneLine(api.Description); d != "" {
		fmt.Fprintf(&b, "%s\n\n", d)
	}
	b.WriteString("Generated by Forge (py-sdk). Do not edit by hand.\n\"\"\"\n\n")

	b.WriteString("from __future__ import annotations\n\n")
	b.WriteString("import base64\n")
	b.WriteString("import json\n")
	b.WriteString("import urllib.error\n")
	b.WriteString("import urllib.parse\n")
	b.WriteString("import urllib.request\n")
	b.WriteString("from dataclasses import dataclass\n")
	b.WriteString("from typing import Any, Dict, Iterator, List, Optional, Union\n\n\n")

	fmt.Fprintf(&b, "DEFAULT_BASE_URL = %s\n\n\n", pyStr(api.BaseURL()))

	// Typed @dataclass models for every named component schema.
	writePyModels(&b, api)

	b.WriteString("class Client:\n")
	b.WriteString("    \"\"\"HTTP client for the API.\"\"\"\n\n")

	b.WriteString("    def __init__(\n")
	b.WriteString("        self,\n")
	b.WriteString("        base_url: Optional[str] = None,\n")
	b.WriteString("        api_key: Optional[str] = None,\n")
	b.WriteString("        username: Optional[str] = None,\n")
	b.WriteString("        password: Optional[str] = None,\n")
	b.WriteString("    ) -> None:\n")
	b.WriteString("        self.base_url = (base_url or DEFAULT_BASE_URL).rstrip(\"/\")\n")
	b.WriteString("        self.api_key = api_key\n")
	b.WriteString("        self.username = username\n")
	b.WriteString("        self.password = password\n\n")

	writePyAuth(&b, api)
	writePyRequest(&b)

	for _, op := range api.SortedOperations() {
		writePyMethod(&b, api, op)
	}

	// Pagination generator methods (one per paginated operation).
	anyPaginated := false
	for _, op := range api.SortedOperations() {
		if op.Pagination != nil {
			writePyPaginator(&b, api, op)
			anyPaginated = true
		}
	}

	// Module-level page helpers backing the iter_* generators.
	if anyPaginated {
		writePyPageHelpers(&b)
	}

	return b.String()
}

// writePyModels emits a @dataclass per named component schema (object schemas)
// or a type alias (everything else), in sorted order. $ref fields resolve to
// the named dataclass. Optional fields default to None. Output is deterministic.
func writePyModels(b *strings.Builder, api *ir.API) {
	names := make([]string, 0, len(api.Schemas))
	for n := range api.Schemas {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, name := range names {
		s := api.Schemas[name]
		typeName := pyClassName(name)
		if typeName == "" {
			continue
		}
		if s == nil || (s.Type != "object" && len(s.Properties) == 0) {
			fmt.Fprintf(b, "%s = %s\n", typeName, pyRefType(api, s))
			if d := oneLine(descOf(s)); d != "" {
				fmt.Fprintf(b, "\"\"\"%s\"\"\"\n", pyDocLine(d))
			}
			b.WriteString("\n\n")
			continue
		}
		required := map[string]bool{}
		for _, r := range s.Required {
			required[r] = true
		}
		propNames := make([]string, 0, len(s.Properties))
		for pn := range s.Properties {
			propNames = append(propNames, pn)
		}
		sort.Strings(propNames)
		// Required fields first (no default), then optional (=None), so the
		// generated dataclass is valid Python.
		var req, opt []string
		for _, pn := range propNames {
			if required[pn] {
				req = append(req, pn)
			} else {
				opt = append(opt, pn)
			}
		}
		b.WriteString("@dataclass\n")
		fmt.Fprintf(b, "class %s:\n", typeName)
		if d := oneLine(descOf(s)); d != "" {
			fmt.Fprintf(b, "    \"\"\"%s\"\"\"\n", pyDocLine(d))
		}
		seen := map[string]bool{}
		emit := func(pn string, withDefault bool) {
			fld := pyFieldName(pn)
			if fld == "" || seen[fld] {
				return
			}
			seen[fld] = true
			pt := pyRefType(api, s.Properties[pn])
			if withDefault {
				fmt.Fprintf(b, "    %s: Optional[%s] = None\n", fld, pt)
			} else {
				fmt.Fprintf(b, "    %s: %s\n", fld, pt)
			}
		}
		for _, pn := range req {
			emit(pn, false)
		}
		for _, pn := range opt {
			emit(pn, true)
		}
		if len(seen) == 0 {
			b.WriteString("    pass\n")
		}
		b.WriteString("\n\n")
	}
}

// writePyPaginator emits an iter_<op>() generator method that yields each page
// of a paginated operation (best-effort; mirrors the Go SDK heuristic). It
// advances the paging argument and stops when a page is empty, so it can never
// loop forever. Arguments mirror the operation method's keyword arguments.
func writePyPaginator(b *strings.Builder, api *ir.API, op ir.Operation) {
	method := pyMethodName(op.ID)
	iterName := "iter_" + method
	pg := op.Pagination

	pageParam := pg.Param
	if pageParam == "" {
		switch pg.Style {
		case "page":
			pageParam = "page"
		case "offset":
			pageParam = "offset"
		default:
			pageParam = "cursor"
		}
	}
	nextField := pg.NextField
	if nextField == "" {
		nextField = "next_cursor"
	}
	pageArg := ""
	for _, p := range op.Params {
		if p.Name == pageParam {
			pageArg = pyParamName(p.Name)
			break
		}
	}
	canAdvance := pageArg != ""

	fmt.Fprintf(b, "    def %s(self, **kwargs: Any) -> Iterator[Any]:\n", iterName)
	fmt.Fprintf(b, "        \"\"\"Iterate every page of %s (style %s, param %s).\n\n",
		method, pyDocLine(pg.Style), pyDocLine(pageParam))
	b.WriteString("        Extra keyword arguments are forwarded to the underlying call.\n")
	b.WriteString("        \"\"\"\n")
	switch pg.Style {
	case "page":
		b.WriteString("        page = 1\n")
	case "offset":
		b.WriteString("        offset = 0\n")
	default:
		b.WriteString("        cursor = None\n")
	}
	b.WriteString("        while True:\n")
	if canAdvance {
		switch pg.Style {
		case "page":
			fmt.Fprintf(b, "            kwargs[%s] = page\n", pyStr(pageArg))
		case "offset":
			fmt.Fprintf(b, "            kwargs[%s] = offset\n", pyStr(pageArg))
		default:
			b.WriteString("            if cursor is not None:\n")
			fmt.Fprintf(b, "                kwargs[%s] = cursor\n", pyStr(pageArg))
		}
	}
	fmt.Fprintf(b, "            result = self.%s(**kwargs)\n", method)
	b.WriteString("            n = _py_page_count(result)\n")
	b.WriteString("            if n == 0:\n                return\n")
	b.WriteString("            yield result\n")
	if !canAdvance {
		b.WriteString("            return\n\n")
		return
	}
	switch pg.Style {
	case "page":
		b.WriteString("            page += 1\n\n")
	case "offset":
		b.WriteString("            offset += n\n\n")
	default:
		fmt.Fprintf(b, "            nxt = _py_page_string(result, %s)\n", pyStr(nextField))
		b.WriteString("            if not nxt:\n                return\n")
		b.WriteString("            cursor = nxt\n\n")
	}
}

// writePyPageHelpers emits the module-level generic JSON inspection helpers used
// by the iter_* generators.
func writePyPageHelpers(b *strings.Builder) {
	b.WriteString("\ndef _py_page_count(v: Any) -> int:\n")
	b.WriteString("    \"\"\"Number of items in a paginated response: a top-level list's length,\n")
	b.WriteString("    else a data/items/results list's length, else 1 for a non-empty dict\n")
	b.WriteString("    and 0 for empty / None.\n    \"\"\"\n")
	b.WriteString("    if isinstance(v, list):\n        return len(v)\n")
	b.WriteString("    if isinstance(v, dict):\n")
	b.WriteString("        for k in (\"data\", \"items\", \"results\"):\n")
	b.WriteString("            if isinstance(v.get(k), list):\n                return len(v[k])\n")
	b.WriteString("        return 0 if not v else 1\n")
	b.WriteString("    return 0 if v is None else 1\n\n\n")

	b.WriteString("def _py_page_string(v: Any, field: str) -> str:\n")
	b.WriteString("    \"\"\"Extract a top-level string field (e.g. the next cursor); '' if absent.\"\"\"\n")
	b.WriteString("    if isinstance(v, dict) and isinstance(v.get(field), str):\n")
	b.WriteString("        return v[field]\n")
	b.WriteString("    return \"\"\n")
}

func writePyAuth(b *strings.Builder, api *ir.API) {
	b.WriteString("    def _apply_auth(self, headers: Dict[str, str], query: Dict[str, Any]) -> None:\n")
	wrote := false
	for _, scheme := range api.Auth {
		switch scheme.Type {
		case "apiKey":
			switch scheme.In {
			case "header":
				fmt.Fprintf(b, "        if self.api_key:\n            headers[%s] = self.api_key\n", pyStr(scheme.KeyName))
				wrote = true
			case "query":
				fmt.Fprintf(b, "        if self.api_key:\n            query[%s] = self.api_key\n", pyStr(scheme.KeyName))
				wrote = true
			}
		case "http":
			switch strings.ToLower(scheme.Scheme) {
			case "bearer":
				b.WriteString("        if self.api_key:\n            headers[\"Authorization\"] = \"Bearer \" + self.api_key\n")
				wrote = true
			case "basic":
				b.WriteString("        if self.username:\n")
				b.WriteString("            raw = f\"{self.username}:{self.password or ''}\".encode()\n")
				b.WriteString("            headers[\"Authorization\"] = \"Basic \" + base64.b64encode(raw).decode()\n")
				wrote = true
			}
		case "oauth2":
			b.WriteString("        if self.api_key:\n            headers[\"Authorization\"] = \"Bearer \" + self.api_key\n")
			wrote = true
		}
	}
	if !wrote {
		b.WriteString("        return\n")
	}
	b.WriteString("\n")
}

func writePyRequest(b *strings.Builder) {
	b.WriteString("    def _request(\n")
	b.WriteString("        self,\n")
	b.WriteString("        method: str,\n")
	b.WriteString("        path: str,\n")
	b.WriteString("        query: Dict[str, Any],\n")
	b.WriteString("        headers: Dict[str, str],\n")
	b.WriteString("        body: Optional[Dict[str, Any]] = None,\n")
	b.WriteString("    ) -> Any:\n")
	b.WriteString("        self._apply_auth(headers, query)\n")
	b.WriteString("        url = self.base_url + path\n")
	b.WriteString("        filtered = {k: v for k, v in query.items() if v is not None}\n")
	b.WriteString("        if filtered:\n")
	b.WriteString("            url += \"?\" + urllib.parse.urlencode({k: str(v) for k, v in filtered.items()})\n")
	b.WriteString("        data = None\n")
	b.WriteString("        if body is not None:\n")
	b.WriteString("            data = json.dumps(body).encode()\n")
	b.WriteString("            headers[\"Content-Type\"] = \"application/json\"\n")
	b.WriteString("        headers[\"Accept\"] = \"application/json\"\n")
	b.WriteString("        req = urllib.request.Request(url, data=data, headers=headers, method=method)\n")
	b.WriteString("        try:\n")
	b.WriteString("            with urllib.request.urlopen(req) as resp:\n")
	b.WriteString("                raw = resp.read().decode()\n")
	b.WriteString("        except urllib.error.HTTPError as exc:\n")
	b.WriteString("            detail = exc.read().decode(errors=\"replace\")\n")
	b.WriteString("            raise RuntimeError(f\"{method} {path} -> HTTP {exc.code}: {detail}\") from exc\n")
	b.WriteString("        return json.loads(raw) if raw else None\n\n")
}

func writePyMethod(b *strings.Builder, api *ir.API, op ir.Operation) {
	name := pyMethodName(op.ID)

	pathParams, queryParams, headerParams := splitParams(op)
	bodyFields := pyBodyFields(api, op)

	// Signature: required params first, then optional ones with defaults.
	type arg struct {
		py       string
		orig     string
		pytype   string
		required bool
		kind     string // path|query|header|body
	}
	var args []arg
	seen := map[string]bool{}
	add := func(orig, pytype string, required bool, kind string) {
		py := pyParamName(orig)
		if seen[py] {
			py = py + "_" + kind
		}
		seen[py] = true
		args = append(args, arg{py: py, orig: orig, pytype: pytype, required: required, kind: kind})
	}
	for _, p := range pathParams {
		add(p.Name, pyType(p.Schema), true, "path")
	}
	for _, p := range queryParams {
		add(p.Name, pyType(p.Schema), p.Required, "query")
	}
	for _, p := range headerParams {
		add(p.Name, pyType(p.Schema), p.Required, "header")
	}
	for _, f := range bodyFields {
		add(f.name, pyType(f.schema), false, "body")
	}

	// Order: required first (stable within their groups).
	var required, optional []arg
	for _, a := range args {
		if a.required {
			required = append(required, a)
		} else {
			optional = append(optional, a)
		}
	}
	ordered := append(append([]arg{}, required...), optional...)

	fmt.Fprintf(b, "    def %s(\n        self,\n", name)
	for _, a := range ordered {
		if a.required {
			fmt.Fprintf(b, "        %s: %s,\n", a.py, a.pytype)
		} else {
			fmt.Fprintf(b, "        %s: Optional[%s] = None,\n", a.py, a.pytype)
		}
	}
	b.WriteString("    ) -> Any:\n")

	if summary := oneLine(firstNonEmpty(op.Summary, op.Description)); summary != "" {
		fmt.Fprintf(b, "        \"\"\"%s\n\n        %s %s\n        \"\"\"\n", pyDocLine(summary), op.Method, op.Path)
	} else {
		fmt.Fprintf(b, "        \"\"\"%s %s\"\"\"\n", op.Method, op.Path)
	}

	// Path.
	fmt.Fprintf(b, "        path = %s\n", pyStr(op.Path))
	for _, a := range ordered {
		if a.kind != "path" {
			continue
		}
		fmt.Fprintf(b, "        path = path.replace(%s, urllib.parse.quote(str(%s)))\n",
			pyStr("{"+a.orig+"}"), a.py)
	}

	// Query.
	b.WriteString("        query: Dict[str, Any] = {}\n")
	for _, a := range ordered {
		if a.kind != "query" {
			continue
		}
		fmt.Fprintf(b, "        if %s is not None:\n            query[%s] = %s\n", a.py, pyStr(a.orig), a.py)
	}

	// Headers.
	b.WriteString("        headers: Dict[str, str] = {}\n")
	for _, a := range ordered {
		if a.kind != "header" {
			continue
		}
		fmt.Fprintf(b, "        if %s is not None:\n            headers[%s] = str(%s)\n", a.py, pyStr(a.orig), a.py)
	}

	// Body.
	hasBody := false
	for _, a := range ordered {
		if a.kind == "body" {
			hasBody = true
			break
		}
	}
	if op.Mutating && hasBody {
		// Use a leading-underscore local so it can never shadow a body field
		// argument literally named "body" (the wrapped-scalar case).
		b.WriteString("        _body: Dict[str, Any] = {}\n")
		for _, a := range ordered {
			if a.kind != "body" {
				continue
			}
			fmt.Fprintf(b, "        if %s is not None:\n            _body[%s] = %s\n", a.py, pyStr(a.orig), a.py)
		}
		fmt.Fprintf(b, "        return self._request(%s, path, query, headers, _body)\n\n", pyStr(op.Method))
	} else if op.Mutating {
		fmt.Fprintf(b, "        return self._request(%s, path, query, headers, {})\n\n", pyStr(op.Method))
	} else {
		fmt.Fprintf(b, "        return self._request(%s, path, query, headers)\n\n", pyStr(op.Method))
	}
}

// pyBodyField is one synthetic request-body field.
type pyBodyField struct {
	name   string
	schema *ir.Schema
}

func pyBodyFields(api *ir.API, op ir.Operation) []pyBodyField {
	if op.RequestBody == nil {
		return nil
	}
	body := api.Resolve(op.RequestBody)
	if body == nil {
		return nil
	}
	if body.Type == "object" || len(body.Properties) > 0 {
		names := make([]string, 0, len(body.Properties))
		for n := range body.Properties {
			names = append(names, n)
		}
		sort.Strings(names)
		out := make([]pyBodyField, 0, len(names))
		for _, n := range names {
			out = append(out, pyBodyField{name: n, schema: body.Properties[n]})
		}
		return out
	}
	return []pyBodyField{{name: "body", schema: body}}
}

func splitParams(op ir.Operation) (path, query, header []ir.Param) {
	for _, p := range op.Params {
		switch p.In {
		case "path":
			path = append(path, p)
		case "query":
			query = append(query, p)
		case "header":
			header = append(header, p)
		}
	}
	return path, query, header
}

func pyType(s *ir.Schema) string {
	if s == nil {
		return "str"
	}
	switch s.Type {
	case "integer":
		return "int"
	case "number":
		return "float"
	case "boolean":
		return "bool"
	case "array":
		return "List[" + pyType(s.Items) + "]"
	case "object":
		return "Dict[str, Any]"
	case "string":
		return "str"
	}
	if len(s.Properties) > 0 {
		return "Dict[str, Any]"
	}
	return "str"
}

// pyRefType is like pyType but resolves a $ref to the generated dataclass name
// (quoted as a forward reference, since models may be defined later or refer to
// each other). Unknown refs degrade to Dict[str, Any]. Used for model fields;
// method params keep pyType (params are scalars).
func pyRefType(api *ir.API, s *ir.Schema) string {
	if s == nil {
		return "Any"
	}
	if s.Ref != "" {
		if api != nil {
			if named, ok := api.Schemas[s.Ref]; ok && named != nil {
				if cn := pyClassName(s.Ref); cn != "" {
					if named.Type == "object" || len(named.Properties) > 0 {
						return pyStr(cn)
					}
					return cn
				}
			}
		}
		return "Dict[str, Any]"
	}
	switch s.Type {
	case "integer":
		return "int"
	case "number":
		return "float"
	case "boolean":
		return "bool"
	case "array":
		return "List[" + pyRefType(api, s.Items) + "]"
	case "string":
		return "str"
	case "object":
		return "Dict[str, Any]"
	}
	if len(s.Properties) > 0 {
		return "Dict[str, Any]"
	}
	return "str"
}

// pyClassName converts a schema name into a PascalCase class identifier.
func pyClassName(s string) string {
	parts := strings.FieldsFunc(s, func(r rune) bool {
		isAlpha := r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z'
		isDigit := r >= '0' && r <= '9'
		return !isAlpha && !isDigit
	})
	var b strings.Builder
	for _, p := range parts {
		if p == "" {
			continue
		}
		r := []rune(p)
		if r[0] >= 'a' && r[0] <= 'z' {
			r[0] -= 32
		}
		b.WriteString(string(r))
	}
	out := b.String()
	if out == "" {
		return ""
	}
	if out[0] >= '0' && out[0] <= '9' {
		out = "Model" + out
	}
	return out
}

// pyFieldName converts a property name into a safe snake_case dataclass field.
func pyFieldName(s string) string { return pyParamName(s) }

// descOf returns a schema's description, or "" for a nil schema.
func descOf(s *ir.Schema) string {
	if s == nil {
		return ""
	}
	return s.Description
}

// pyMethodName converts an operation ID into a snake_case method name.
func pyMethodName(s string) string {
	n := snake(s)
	if n == "" {
		return "call"
	}
	if pyKeywords[n] {
		n += "_"
	}
	return n
}

// pyParamName converts a parameter name into a safe snake_case identifier.
func pyParamName(s string) string {
	n := snake(s)
	if n == "" {
		return "arg"
	}
	if pyKeywords[n] {
		n += "_"
	}
	return n
}

// snake lower-cases and splits camelCase / non-alphanumeric runs into snake_case.
func snake(s string) string {
	var b strings.Builder
	prevLower := false
	prevSep := true
	for _, r := range s {
		switch {
		case r >= 'A' && r <= 'Z':
			if prevLower && !prevSep {
				b.WriteByte('_')
			}
			b.WriteRune(r + 32)
			prevLower = false
			prevSep = false
		case r >= 'a' && r <= 'z':
			b.WriteRune(r)
			prevLower = true
			prevSep = false
		case r >= '0' && r <= '9':
			if b.Len() == 0 {
				b.WriteByte('n')
			}
			b.WriteRune(r)
			prevLower = false
			prevSep = false
		default:
			if !prevSep && b.Len() > 0 {
				b.WriteByte('_')
			}
			prevSep = true
			prevLower = false
		}
	}
	return strings.Trim(b.String(), "_")
}

var pyKeywords = map[string]bool{
	"and": true, "as": true, "assert": true, "async": true, "await": true,
	"break": true, "class": true, "continue": true, "def": true, "del": true,
	"elif": true, "else": true, "except": true, "finally": true, "for": true,
	"from": true, "global": true, "if": true, "import": true, "in": true,
	"is": true, "lambda": true, "nonlocal": true, "not": true, "or": true,
	"pass": true, "raise": true, "return": true, "try": true, "while": true,
	"with": true, "yield": true, "None": true, "True": true, "False": true,
}

// pyStr renders s as a single-quoted-safe Python double-quoted string literal.
func pyStr(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch r {
		case '"':
			b.WriteString("\\\"")
		case '\\':
			b.WriteString("\\\\")
		case '\n':
			b.WriteString("\\n")
		case '\r':
			b.WriteString("\\r")
		case '\t':
			b.WriteString("\\t")
		default:
			b.WriteRune(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}

// pyDocLine sanitizes a docstring line so it cannot terminate the docstring.
func pyDocLine(s string) string {
	s = strings.ReplaceAll(s, "\"\"\"", "'''")
	s = strings.ReplaceAll(s, "\\", "\\\\")
	return s
}

func oneLine(s string) string {
	s = strings.TrimSpace(s)
	if i := strings.IndexByte(s, '\n'); i >= 0 {
		s = strings.TrimSpace(s[:i])
	}
	if len(s) > 200 {
		s = s[:199] + "…"
	}
	return s
}

func firstNonEmpty(vals ...string) string {
	for _, v := range vals {
		if strings.TrimSpace(v) != "" {
			return v
		}
	}
	return ""
}
