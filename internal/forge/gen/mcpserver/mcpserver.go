// Package mcpserver generates a standalone Go MCP server for an API. The emitted
// program embeds the tool catalog and proxies tools/call to the upstream REST
// API over either stdio or Streamable HTTP — a generalization of the in-repo
// rysh-mcp-samples (mcp-server = stdio, mcp-rest-api-wrapper = HTTP).
package mcpserver

import (
	"encoding/json"
	"fmt"
	"sort"
	"strings"

	"github.com/rysh-ai/rysh-cli-code/internal/forge/gen"
	"github.com/rysh-ai/rysh-cli-code/internal/forge/ir"
)

func init() { gen.Register(&generator{}) }

type generator struct{}

func (g *generator) Name() string { return "mcp-server" }

// emittedTool is the tools/list entry baked into the generated server.
type emittedTool struct {
	Name        string          `json:"name"`
	Description string          `json:"description"`
	InputSchema json.RawMessage `json:"inputSchema"`
}

func (g *generator) Generate(api *ir.API, opts gen.Options) (*gen.FileSet, error) {
	var tools []emittedTool
	var opsLit strings.Builder
	ops := api.SortedOperations()
	for i := range ops {
		op := &ops[i]
		name := sanitize(opts.Prefix + op.ID)
		desc := op.Summary
		if desc == "" {
			desc = fmt.Sprintf("%s %s", op.Method, op.Path)
		}
		tools = append(tools, emittedTool{Name: name, Description: desc, InputSchema: op.ToolInputSchema(api)})

		var pathP, queryP, headerP []string
		for _, p := range op.Params {
			switch p.In {
			case "path":
				pathP = append(pathP, p.Name)
			case "query":
				queryP = append(queryP, p.Name)
			case "header":
				headerP = append(headerP, p.Name)
			}
		}
		fmt.Fprintf(&opsLit, "\t%q: {Method: %q, Path: %q, PathParams: %s, QueryParams: %s, HeaderParams: %s, HasBody: %v},\n",
			name, op.Method, op.Path, goStrSlice(pathP), goStrSlice(queryP), goStrSlice(headerP), op.Mutating)
	}

	toolsJSON, err := json.MarshalIndent(tools, "", "  ")
	if err != nil {
		return nil, err
	}

	authMode, authKey := authInfo(api)
	module := opts.ModulePath
	if module == "" {
		module = "example.com/" + api.Slug() + "-mcp"
	}

	// Scalars are inserted as already-quoted Go string literals; the tool
	// catalog is embedded via a separate tools.json (go:embed) to avoid any
	// escaping issues with descriptions.
	main := strings.NewReplacer(
		"__BASE_URL__", fmt.Sprintf("%q", api.BaseURL()),
		"__SERVER_NAME__", fmt.Sprintf("%q", api.Slug()+"-mcp"),
		"__AUTH_MODE__", fmt.Sprintf("%q", authMode),
		"__AUTH_KEY__", fmt.Sprintf("%q", authKey),
		"__OPS_LITERAL__", opsLit.String(),
	).Replace(serverTemplate)

	fs := gen.NewFileSet()
	fs.AddString("go.mod", fmt.Sprintf("module %s\n\ngo 1.22\n", module))
	fs.AddString("main.go", main)
	fs.Add("tools.json", toolsJSON)
	fs.AddString("README.md", readme(api))
	return fs, nil
}

func authInfo(api *ir.API) (mode, key string) {
	for _, a := range api.Auth {
		switch a.Type {
		case "apiKey":
			if a.In == "query" {
				return "apikey_query", a.KeyName
			}
			return "apikey_header", a.KeyName
		case "http":
			if strings.ToLower(a.Scheme) == "bearer" {
				return "bearer", "Authorization"
			}
			if strings.ToLower(a.Scheme) == "basic" {
				return "basic", "Authorization"
			}
		case "oauth2":
			return "bearer", "Authorization"
		}
	}
	return "none", ""
}

func readme(api *ir.API) string {
	return fmt.Sprintf(`# %s — generated MCP server

Generated by Rysh Forge from a %s spec (%d operations).

## Run

stdio (default):

    go run .

Streamable HTTP:

    go run . --http :8080
    # MCP endpoint: POST http://localhost:8080/mcp

## Configuration (environment)

- API_KEY    — credential injected per the API's auth scheme
- API_USER / API_PASS — for HTTP basic auth
- BASE_URL   — override the upstream base URL (default %q)

Register with an MCP client, e.g. Claude Code:

    claude mcp add --transport http %s http://localhost:8080/mcp
`, api.Name, api.SourceType, len(api.Operations), api.BaseURL(), api.Slug())
}

func goStrSlice(xs []string) string {
	if len(xs) == 0 {
		return "nil"
	}
	sort.Strings(xs)
	quoted := make([]string, len(xs))
	for i, x := range xs {
		quoted[i] = fmt.Sprintf("%q", x)
	}
	return "[]string{" + strings.Join(quoted, ", ") + "}"
}

func sanitize(s string) string {
	var b strings.Builder
	for _, r := range s {
		switch {
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z', r >= '0' && r <= '9', r == '_', r == '-':
			b.WriteRune(r)
		default:
			b.WriteByte('_')
		}
	}
	out := b.String()
	for strings.Contains(out, "__") {
		out = strings.ReplaceAll(out, "__", "_")
	}
	out = strings.Trim(out, "_")
	if out == "" {
		out = "tool"
	}
	if len(out) > 64 {
		out = out[:64]
	}
	return out
}
