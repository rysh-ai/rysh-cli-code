package importer

import (
	"fmt"
	"strings"
)

// ScriptVerbs are the only ## commands a generated script uses: ##new (tab,
// lane, pane), ##tab (list, name) and ##cmd (send a pane its start text).
var ScriptVerbs = []string{"new", "tab", "cmd"}

// Script renders a plan's layout as a .rysh script (design 021) that builds
// it in the session it is run in.
//
// Two properties are load-bearing. First, the import runs nothing: a start
// command is text in this file until the user runs it with `rysh script`,
// and then it runs in its new pane. Second, no imported text is ever written
// on a ## line. A ## line's body is a bash double-quoted string and its tail
// (from the first && | ; > …) is bash run in the SCRIPT's shell, so a start
// command like `tail -f log | grep x` written there would run its pipe at
// script time. Each value is instead a single-quoted plain bash assignment,
// and the ## line refers to it by variable.
func Script(p *Plan) string {
	var b strings.Builder
	path := p.scriptPath()
	b.WriteString("#!/usr/bin/env -S rysh script\n")
	fmt.Fprintf(&b, "# Generated by `rysh import %s`. Review it, then run it inside the session\n", p.Source)
	b.WriteString("# that should get this layout:\n")
	fmt.Fprintf(&b, "#   rysh script %s\n", path)
	b.WriteString("# Each start command below runs in its new pane when you run this script;\n")
	b.WriteString("# the import itself ran nothing.\n")
	b.WriteString("set -euo pipefail\n\n")
	b.WriteString("# The id of the newest tab: the last id= field that ##tab list printed.\n")
	b.WriteString("newest_tab() { printf '%s\\n' \"${RYSH_OUT:-}\" | sed -n 's/.* id=\\([^ ]*\\).*/\\1/p' | tail -n 1; }\n")
	for ti, tab := range p.Tabs {
		lanes, panes := 0, 0
		for _, l := range tab.Lanes {
			lanes++
			panes += len(l.Panes)
		}
		fmt.Fprintf(&b, "\n# tab %d: %d lane(s), %d pane(s)\n", ti+1, lanes, panes)
		b.WriteString("##new tab\n##tab list\n")
		b.WriteString("t=\"$(newest_tab)\"\n")
		b.WriteString("[ -n \"$t\" ] || { echo 'rysh import: could not find the new tab (run this file with rysh script)' >&2; exit 1; }\n")
		fmt.Fprintf(&b, "name=%s\n", shellQuote(tab.Name))
		b.WriteString("##tab name $t $name\n")
		for li, lane := range tab.Lanes {
			if li > 0 {
				b.WriteString("##new lane $t\n")
			}
			for pi := 1; pi < len(lane.Panes); pi++ {
				fmt.Fprintf(&b, "##new pane $t %d\n", li+1)
			}
			for pi, pane := range lane.Panes {
				text := paneStartText(pane)
				if text == "" {
					continue
				}
				if pane.Name != "" {
					fmt.Fprintf(&b, "# pane %q\n", oneLine(pane.Name))
				}
				fmt.Fprintf(&b, "c=%s\n", shellQuote(text))
				fmt.Fprintf(&b, "##cmd stack --tab $t --lane %d --pg %d -- $c\n", li+1, pi+1)
			}
		}
	}
	return b.String()
}

// paneStartText is what a new pane's shell is sent: a cd to its directory,
// then its start command.
func paneStartText(p Pane) string {
	var parts []string
	if p.Cwd != "" {
		parts = append(parts, "cd -- "+cwdWord(p.Cwd))
	}
	if p.Command != "" {
		parts = append(parts, p.Command)
	}
	return strings.Join(parts, " && ")
}

// cwdWord quotes a directory for the pane's shell, leaving a leading $HOME
// for that shell to expand.
func cwdWord(cwd string) string {
	switch {
	case cwd == "$HOME":
		return `"$HOME"`
	case strings.HasPrefix(cwd, "$HOME/"):
		return `"$HOME"/` + shellQuote(strings.TrimPrefix(cwd, "$HOME/"))
	}
	return shellQuote(cwd)
}

func oneLine(s string) string {
	return strings.NewReplacer("\n", " ", "\r", " ").Replace(s)
}
